"""Checks of the book's sources and of a finished build, run by tools/build.sh after the PDF and by anyone before a
commit. Exit status 1 on an error; warnings are printed for the editor and do not fail.

Errors (each rule is in CLAUDE.md):
- a source file (.tex, .bib) that is not ASCII;
- \\footnote or \\marginnote in a chapter (use \\sidenote or \\mnote);
- a hand-edited file in data/ (every file there must carry the generator's header);
- in the log: a LaTeX error, an undefined reference or citation, an overfull box wider than 1 pt, or a warning
  that labels may have changed (the build needs another run).
Warnings:
- a number with four or more significant digits, or in scientific notation, typed directly in a chapter: numbers
  quoted from computations must come from data/values.tex (\\val...); the editor checks each warning.

Usage: python tools/check.py [path/to/main.log]
"""
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent.parent
GENERATED_HEADER = 'Generated by tools/generate_data.cpp'


def main() -> int:
    errors, warnings = [], []
    for path in sorted(list(HERE.glob('*.tex')) + list(HERE.glob('*.bib')) + list(HERE.glob('chapters/*.tex'))
                       + list(HERE.glob('figures/*.tex'))):
        text = path.read_bytes()
        try:
            text.decode('ascii')
        except UnicodeDecodeError as e:
            line = text[:e.start].count(b'\n') + 1
            errors.append(f'{path.relative_to(HERE)}:{line}: non-ASCII byte (use LaTeX commands, CLAUDE.md "Sources")')
    for path in sorted(HERE.glob('chapters/*.tex')):
        for n, line in enumerate(path.read_text(encoding='ascii', errors='replace').splitlines(), 1):
            code = line.split('%', 1)[0]
            if re.search(r'\\footnote\b|\\marginnote\b', code):
                errors.append(f'{path.relative_to(HERE)}:{n}: \\footnote or \\marginnote (use \\sidenote or \\mnote)')
            for number in re.findall(r'(?<![\w\\{])(\d+\.\d{3,}|\d+(?:\.\d+)?[eE][-+]?\d+)(?![\w}])', code):
                warnings.append(f'{path.relative_to(HERE)}:{n}: typed number {number} (from data/values.tex?)')
    for path in sorted(HERE.glob('data/*')):
        if path.name == 'README.md' or path.is_dir():
            continue
        head = path.read_text(encoding='ascii', errors='replace')[:300]
        if GENERATED_HEADER not in head:
            errors.append(f'{path.relative_to(HERE)}: not written by the generator (no "{GENERATED_HEADER}" header)')
    if len(sys.argv) > 1:
        log = pathlib.Path(sys.argv[1]).read_text(encoding='latin-1')
        for pattern, message in ((r'^! .*', 'LaTeX error'),
                                 (r'LaTeX Warning: (Reference|Citation) .* undefined.*', 'undefined'),
                                 (r'Package natbib Warning: Citation .* undefined.*', 'undefined citation'),
                                 (r'LaTeX Warning: Label\(s\) may have changed.*', 'rerun needed')):
            for m in re.finditer(pattern, log, re.MULTILINE):
                errors.append(f'log: {message}: {m.group(0).strip()}')
        for m in re.finditer(r'Overfull \\[hv]box \((\d+(?:\.\d+)?)pt too \w+\)[^\n]*', log):
            if float(m.group(1)) > 1.0:
                errors.append(f'log: {m.group(0).strip()}')
    for w in warnings:
        print('warning:', w)
    for e in errors:
        print('error:', e)
    print(f'check: {len(errors)} error(s), {len(warnings)} warning(s)')
    return 1 if errors else 0


if __name__ == '__main__':
    sys.exit(main())
