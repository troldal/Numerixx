"""Checks of the book's sources and of a finished build, run by tools/build.sh after the PDF and by anyone before a
commit. Exit status 1 on an error; warnings are printed for the editor and do not fail.

Errors (each rule is in CLAUDE.md):
- a source file (.tex, .bib) that is not ASCII;
- \\footnote or \\marginnote in a chapter (use \\sidenote or \\mnote);
- a \\snippet or \\snippetheader whose file does not exist or whose markers "// <name>" and "// </name>" are
  missing or enclose no line (listings would print nothing, or the wrong lines, without a warning); a \\cmakefile
  whose file does not exist;
- a \\code{...} line of a `signature` block (the transcribed declarations of Chapter 8, PLAN.md section 8) that does
  not occur, comments stripped and whitespace removed, in include/numerixx/deriv.hpp or math.hpp (a drift of the
  header from the book);
- a hand-edited file in data/ (every file there must carry the generator's header);
- in the log: a LaTeX error, an undefined reference or citation, an overfull box wider than 1 pt, or a warning
  that labels may have changed (the build needs another run).
Warnings:
- a number with four or more significant digits, or in scientific notation, typed directly in a chapter: numbers
  quoted from computations must come from data/values.tex (\\val...); the editor checks each warning.

Usage: python tools/check.py [path/to/main.log]
"""
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent.parent
GENERATED_HEADER = 'Generated by tools/generate_data.cpp'


def snippet_problem(source: pathlib.Path, marker: str) -> str:
    """Why \\snippet would quote nothing or the wrong lines: a missing file, a missing or repeated marker, or an
    empty range. Markers are the comment lines "// <marker>" and "// </marker>" in column 0."""
    if not source.is_file():
        return f'no file {source.relative_to(HERE)}'
    lines = source.read_text(encoding='ascii', errors='replace').splitlines()
    starts = [i for i, l in enumerate(lines) if l.rstrip() == f'// <{marker}>']
    ends = [i for i, l in enumerate(lines) if l.rstrip() == f'// </{marker}>']
    if len(starts) != 1 or len(ends) != 1:
        return f'marker <{marker}> found {len(starts)} time(s) and </{marker}> {len(ends)} time(s) in {source.name}'
    if ends[0] <= starts[0] + 1:
        return f'the snippet <{marker}> in {source.name} is empty'
    return ''


def normalised_code(text: str) -> str:
    """C++ text with its comments stripped and every whitespace character removed, for a comparison that ignores
    line breaks and the header's documentation comments."""
    text = re.sub(r'/\*.*?\*/', ' ', text, flags=re.S)
    text = re.sub(r'//[^\n]*', ' ', text)
    return re.sub(r'\s+', '', text)


def signature_problems() -> list:
    """The declarations of every `signature` block (Chapter 8) that do not occur in the library's headers: the
    declarations are transcribed, and this keeps them true to the header. The \\code{...} lines of a block are joined
    into one declaration up to the line that ends it (a semicolon or a brace), whitespace and comments removed, and
    the whole must occur in the headers normalised the same way: a line-by-line check would pass a change confined to
    one of two overloads that share their other lines (R2-library-03). A comment line, a namespace line (presentation:
    the header nests its namespaces) and a "see below" placeholder comment are skipped or stripped."""
    headers = ''
    for name in ('deriv.hpp', 'math.hpp'):
        headers += (HERE.parent.parent / 'include' / 'numerixx' / name).read_text(encoding='utf-8', errors='replace')
        headers += '\n'
    normalised_headers = normalised_code(headers)
    problems = []
    for path in sorted(HERE.glob('chapters/*.tex')):
        text = path.read_text(encoding='ascii', errors='replace')
        for block in re.finditer(r'\\begin\{signature\}(.*?)\\end\{signature\}', text, flags=re.S):
            declaration, first = [], ''

            def check() -> None:
                whole = ''.join(declaration).rstrip(';')
                if whole and whole not in normalised_headers:
                    problems.append(f'{path.relative_to(HERE)}: declaration not in the headers: {first} ...')

            # A brace that the chapter sets outside \code (\texttt{\{}, \texttt{\};}) is part of the declaration.
            body = block.group(1).replace('\\texttt{\\{}', '\\code{ BRACEOPEN }').replace('\\texttt{\\};}', '\\code{ BRACECLOSE ;}')
            for piece in re.findall(r'\\code\{((?:[^{}]|\{[^{}]*\})*)\}', body):
                stripped = piece.strip().replace('BRACEOPEN', '{').replace('BRACECLOSE', '}')
                if stripped.startswith('//') or stripped.startswith('namespace'):
                    continue
                code = normalised_code(stripped)
                if not code:
                    continue
                if not declaration:
                    first = stripped
                declaration.append(code)
                if stripped.endswith((';', '{', '}')):
                    check()
                    declaration, first = [], ''
            check()
    return problems


def main() -> int:
    errors, warnings = [], []
    for path in sorted(list(HERE.glob('*.tex')) + list(HERE.glob('*.bib')) + list(HERE.glob('chapters/*.tex'))
                       + list(HERE.glob('figures/*.tex'))):
        text = path.read_bytes()
        try:
            text.decode('ascii')
        except UnicodeDecodeError as e:
            line = text[:e.start].count(b'\n') + 1
            errors.append(f'{path.relative_to(HERE)}:{line}: non-ASCII byte (use LaTeX commands, CLAUDE.md "Sources")')
    for path in sorted(HERE.glob('chapters/*.tex')):
        for n, line in enumerate(path.read_text(encoding='ascii', errors='replace').splitlines(), 1):
            code = line.split('%', 1)[0]
            if re.search(r'\\footnote\b|\\marginnote\b', code):
                errors.append(f'{path.relative_to(HERE)}:{n}: \\footnote or \\marginnote (use \\sidenote or \\mnote)')
            for number in re.findall(r'(?<![\w\\{])(\d+\.\d{3,}|\d+(?:\.\d+)?[eE][-+]?\d+)(?![\w}])', code):
                warnings.append(f'{path.relative_to(HERE)}:{n}: typed number {number} (from data/values.tex?)')
            for macro, name, marker in re.findall(r'\\(snippet|snippetheader)\{([^}]*)\}\{([^}]*)\}', code):
                source = HERE / 'code' / (name + ('.hpp' if macro == 'snippetheader' else '.cpp'))
                problem = snippet_problem(source, marker)
                if problem:
                    errors.append(f'{path.relative_to(HERE)}:{n}: \\{macro}{{{name}}}{{{marker}}}: {problem}')
            for name in re.findall(r'\\cmakefile\{([^}]*)\}', code):
                if not (HERE / 'code' / (name + '.cmake')).is_file():
                    errors.append(f'{path.relative_to(HERE)}:{n}: \\cmakefile{{{name}}}: no file code/{name}.cmake')
    errors.extend(signature_problems())
    for path in sorted(HERE.glob('data/*')):
        if path.name == 'README.md' or path.is_dir():
            continue
        head = path.read_text(encoding='ascii', errors='replace')[:300]
        if GENERATED_HEADER not in head:
            errors.append(f'{path.relative_to(HERE)}: not written by the generator (no "{GENERATED_HEADER}" header)')
    if len(sys.argv) > 1:
        log = pathlib.Path(sys.argv[1]).read_text(encoding='latin-1')
        for pattern, message in ((r'^! .*', 'LaTeX error'),
                                 (r'LaTeX Warning: (Reference|Citation) .* undefined.*', 'undefined'),
                                 (r'Package natbib Warning: Citation .* undefined.*', 'undefined citation'),
                                 (r'LaTeX Warning: Label\(s\) may have changed.*', 'rerun needed')):
            for m in re.finditer(pattern, log, re.MULTILINE):
                errors.append(f'log: {message}: {m.group(0).strip()}')
        for m in re.finditer(r'Overfull \\[hv]box \((\d+(?:\.\d+)?)pt too \w+\)[^\n]*', log):
            if float(m.group(1)) > 1.0:
                errors.append(f'log: {m.group(0).strip()}')
    for w in warnings:
        print('warning:', w)
    for e in errors:
        print('error:', e)
    print(f'check: {len(errors)} error(s), {len(warnings)} warning(s)')
    return 1 if errors else 0


if __name__ == '__main__':
    sys.exit(main())
