    // The nine functions of the random study with their derivatives of order 1 to 4 in closed form.
    double falling(double a, int n)
    {
        double r = 1;
        for (int i = 0; i < n; ++i) r *= a - i;
        return r;
    }

    long long factorial(int n) { return n <= 1 ? 1 : n * factorial(n - 1); }

    // Powers are formed by multiplication (ipow), never by libm's pow, so that the references are reproducible.
    double sin_n(int n, double x) { return std::sin(x + n * std::numbers::pi / 2); }
    double log_n(int n, double x) { return (n % 2 == 1 ? 1 : -1) * static_cast<double>(factorial(n - 1)) / ipow(x, n); }
    double sqrt_n(int n, double x) { return falling(0.5, n) * std::sqrt(x) / ipow(x, n); }
    double inverse_n(int n, double x) { return (n % 2 == 0 ? 1 : -1) * static_cast<double>(factorial(n)) / ipow(x, n + 1); }
    // 1/(1 + 25 x^2) = Re 1/(1 + 5ix), whose n-th derivative is (-1)^n n! (5i)^n (1 + 5ix)^-(n+1); (5i)^n is exact.
    double runge_n(int n, double x)
    {
        std::complex<double> const z(1.0, 5.0 * x);
        std::complex<double> zn(1.0, 0.0);
        for (int i = 0; i <= n; ++i) zn *= z;
        std::complex<double> c(static_cast<double>(factorial(n)), 0.0);
        for (int i = 0; i < n; ++i) c *= std::complex<double>(0.0, 5.0);
        return ((n % 2 == 0 ? c : -c) / zn).real();
    }
    double quintic_n(int n, double x) { return falling(5, n) * ipow(x, 5 - n); }
    // d^n/dx^n exp(-x^2) = (-1)^n H_n(x) exp(-x^2), with the physicists' Hermite polynomials.
    double gauss_n(int n, double x)
    {
        double const g = std::exp(-x * x);
        switch (n) {
            case 1: return -(2 * x) * g;
            case 2: return (4 * x * x - 2) * g;
            case 3: return -(8 * x * x * x - 12 * x) * g;
            default: return (16 * x * x * x * x - 48 * x * x + 12) * g;
        }
    }
    // With t = tanh x and s = 1 - t^2: t' = s, t'' = -2ts, t''' = s(6t^2 - 2), t'''' = 8ts(2 - 3t^2).
    double tanh_n(int n, double x)
    {
        double const t = std::tanh(x);
        double const s = 1 - t * t;
        switch (n) {
            case 1: return s;
            case 2: return -2 * t * s;
            case 3: return s * (6 * t * t - 2);
            default: return 8 * t * s * (2 - 3 * t * t);
        }
    }

