    void ds11_newton(Output &o)
    {
        // T from H(T) = H(T*), T* = T0, from 200 K below, with the slope from derivative(H, T).
        double const H_star = H(T0);
        auto out = csv(o, "newton", "iteration,T,residual,error",
            "Newton for T with H(T) = H(1000 K) from T = 800 K, slope by Central<2> with the default step; residual in J/mol, "
            "error |T - 1000| in K");
        double T = T0 - 200;
        int iterations = 0;
        double residual = H(T) - H_star;
        out << 0 << ',' << cell(T) << ',' << cell(residual) << ',' << cell(std::abs(T - T0)) << '\n';
        for (int n = 1; n <= 20; ++n) {
            auto const slope = derivative(H, T);
            if (!slope) {
                o.fail("DS11: the slope is not finite");
                break;
            }
            double const dT = residual / slope->value;
            T -= dT;
            residual = H(T) - H_star;
            iterations = n;
            out << n << ',' << cell(T) << ',' << cell(residual) << ',' << cell(std::abs(T - T0)) << '\n';
            if (std::abs(dT) < 1e-9) break;
        }
        value(o, "NewtonIterations", integer(iterations));
        value(o, "NewtonFinalError", sig(std::abs(T - T0)));
        value(o, "NewtonFinalResidual", sig(std::abs(residual)));
        value(o, "NewtonStart", sig(T0 - 200, 3));
    }

    // ------------------------------------------------------------------------------------------------ E18

    // The checks of code/07-using-check.cpp (section 7.5), recomputed as the example computes them: the agreeing
    // digits between Central<2> at h, 2h and h/2 and against Central<4>; |d - r| against Ridders; and sin x just
    // above pi/2, where f' is near 0, with the digits counted against f' and against the scale |f| / max(|x|, 1).
    void e18_check(Output &o)
    {
        auto const digits = [](double a, double b) { return a == b ? 16.0 : -std::log10(std::abs(a - b) / std::abs(b)); };
        double const exact = Hn(1);
        double const h = nxx::math::root_epsilon<3, double>() * T0;
        auto const d = derivative(H, T0, h);
        auto const d2 = derivative(H, T0, 2 * h);
        auto const d0 = derivative(H, T0, h / 2);
        auto const c4 = derivative<Central<4>>(H, T0);
        auto const r = derivative<Ridders>(H, T0);
        if (!d || !d2 || !d0 || !c4 || !r) {
            o.fail("E18: a derivative failed");
            return;
        }
        value(o, "CheckStepsDigits", fixed(std::min(digits(d2->value, d->value), digits(d0->value, d->value)), 1));
        value(o, "CheckExactDigits", fixed(digits(d->value, exact), 1));
        value(o, "CheckOrderDigits", fixed(digits(d->value, c4->value), 1));
        value(o, "CheckRiddersDiff", sig(std::abs(d->value - r->value)));
        value(o, "CheckStencilActual", sig(std::abs(d->value - exact)));
        value(o, "CheckRiddersEstimate", sig(*r->abs_error));
        auto const sine = [](double x) { return std::sin(x); };
        double const x = 1.5708;
        double const hs = nxx::math::root_epsilon<3, double>() * x;
        auto const s = derivative(sine, x, hs);
        auto const s2 = derivative(sine, x, 2 * hs);
        auto const s0 = derivative(sine, x, hs / 2);
        if (!s || !s2 || !s0) {
            o.fail("E18: the sine derivatives failed");
            return;
        }
        double const spread = std::max(std::abs(s2->value - s->value), std::abs(s0->value - s->value));
        double const scale = std::abs(sine(x)) / x;
        value(o, "CheckSineDerivative", sig(s->value, 4));
        value(o, "CheckSineAbsError", sig(std::abs(s->value - std::cos(x))));
        value(o, "CheckSineRelError", sig(std::abs(s->value - std::cos(x)) / std::abs(std::cos(x))));
        value(o, "CheckSineSpread", sig(spread));
        value(o, "CheckSineDigitsDerivative", fixed(-std::log10(spread / std::abs(s->value)), 1));
        value(o, "CheckSineDigitsScale", fixed(-std::log10(spread / scale), 1));
    }

