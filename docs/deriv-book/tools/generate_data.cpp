    template<typename M, int N, typename F>
    std::expected<Estimate<float>, nxx::deriv::error> float_default(F fn, float x)
    { return derivative<M, N>(fn, x); }
#if defined(_MSC_VER) && !defined(__clang__)
#pragma warning(pop)
#else
#pragma GCC diagnostic pop
#endif

    // The relative error of method M for the N-th derivative of exp at x with the default step, in double and float
    // (every derivative of exp equals exp, so the relative error is |d - exp(x)| / exp(x)).
    template<typename M, int N>
    std::optional<double> exp_default_double(double x)
    { return rel_error(derivative<M, N>(exp_fn, x), std::exp(x)); }

    template<typename M, int N>
    std::optional<double> exp_default_float(double x)
    {
        auto const expf_fn = [](float t) { return std::exp(t); };
        return rel_error_t(float_default<M, N>(expf_fn, static_cast<float>(x)), std::exp(static_cast<float>(x)));
    }

    // Ridders over the typical points: the median relative error, relative estimate and evaluation count.
    struct RiddersTypical
    {
        std::optional<double> error;
        std::optional<double> estimate;
        long long evaluations;
    };

    // M is Ridders or one of its one-sided forms.
    template<typename M, int N>
    RiddersTypical ridders_typical_double()
    {
        std::vector<double> errors;
        std::vector<double> estimates;
        std::vector<double> calls;
        for (double const x : typical_points) {
            int n = 0;
            auto const r = derivative<M, N>(Counted{ exp_fn, &n }, x);
            if (!r) continue;
            errors.push_back(std::abs(r->value - std::exp(x)) / std::exp(x));
            estimates.push_back(*r->abs_error / std::exp(x));
            calls.push_back(n);
        }
        std::sort(calls.begin(), calls.end());
        return { median(errors), median(estimates), calls.empty() ? 0 : static_cast<long long>(calls[calls.size() / 2]) };
    }

    template<typename M, int N>
    RiddersTypical ridders_typical_float()
    {
        auto const expf_fn = [](float t) { return std::exp(t); };
        std::vector<double> errors;
        std::vector<double> estimates;
        std::vector<double> calls;
        for (double const x : typical_points) {
            int n = 0;
            float const xf = static_cast<float>(x);
            auto const r = float_default<M, N>(Counted{ expf_fn, &n }, xf);
            if (!r) continue;
            double const exact = static_cast<double>(std::exp(xf));
            errors.push_back(std::abs(static_cast<double>(r->value) - exact) / exact);
            estimates.push_back(static_cast<double>(*r->abs_error) / exact);
            calls.push_back(n);
        }
        std::sort(calls.begin(), calls.end());
        return { median(errors), median(estimates), calls.empty() ? 0 : static_cast<long long>(calls[calls.size() / 2]) };
    }

