    void ds8_ridders_tableau(Output &o)
    {
        constexpr std::size_t levels = 16;
        double const cp = Hn(1);
        std::array<std::array<double, levels>, levels> A{};
        std::array<double, levels> floors{};
        std::array<double, levels> hs{};
        double h = T0 / 32; // the library's default initial step for f': scale(x) / 32, exact
        for (std::size_t i = 0; i < levels; ++i, h = h / 2) {
            hs[i] = h;
            auto const d = derivative<Central<2>>(H, T0, h);
            if (!d) {
                o.fail("DS8: the base difference at level " + std::to_string(i) + " is not finite");
                return;
            }
            A[i][0] = d->value;
            // The rounding floor as the tests define it: (eps |f(x - h)| + eps |f(x + h)|) / ((x + h) - (x - h)).
            double const lo = T0 - h;
            double const hi = T0 + h;
            floors[i] = (dbl_eps * std::abs(H(lo)) + dbl_eps * std::abs(H(hi))) / (hi - lo);
            // Burden's difference form, as the library computes it.
            double factor = 1;
            for (std::size_t j = 1; j <= i; ++j) {
                factor = factor * 4;
                double const correction = (A[i][j - 1] - A[i - 1][j - 1]) / (factor - 1);
                A[i][j] = A[i][j - 1] + correction;
            }
        }

        // Ridders' own run: the stop from the evaluation count, the returned entry matched bit for bit.
        int calls = 0;
        auto const r = derivative<Ridders>(Counted{ H, &calls }, T0);
        if (!r || calls % 2 != 0) {
            o.fail("DS8: Ridders on the nitrogen example failed or restarted");
            return;
        }
        std::size_t const used = static_cast<std::size_t>(calls / 2);
        std::optional<std::pair<std::size_t, std::size_t>> best;
        for (std::size_t i = 0; i < std::min(used, levels) && !best; ++i)
            for (std::size_t j = 0; j <= i; ++j)
                if (A[i][j] == r->value) {
                    best = { i, j };
                    break;
                }
        if (!best) {
            o.fail("DS8: Ridders' returned value matches no tableau entry bit for bit");
            return;
        }
        value(o, "TableauLevelsUsed", integer(static_cast<long long>(used)));
        value(o, "TableauStopLevel", integer(static_cast<long long>(used) - 1));
        value(o, "TableauBestLevel", integer(static_cast<long long>(best->first)));
        value(o, "TableauBestColumn", integer(static_cast<long long>(best->second)));
        value(o, "TableauLevels", integer(static_cast<long long>(levels)));
        // The level at which the base difference alone is most accurate.
        Minimum base_best;
        for (std::size_t i = 0; i < levels; ++i) base_best.offer(static_cast<double>(i), std::abs(A[i][0] - cp) / cp);
        value(o, "TableauBaseBestLevel", integer(static_cast<long long>(base_best.h)));
        value(o, "TableauBaseBestRelError", sig(base_best.error));
        value(o, "TableauBaseFirstRelError", sig(std::abs(A[0][0] - cp) / cp));
        value(o, "TableauBestRelError", sig(std::abs(A[best->first][best->second] - cp) / cp));

        auto out = csv(o, "ridders-tableau", "i,j,h,A,error,estimate,floor",
            "nitrogen cp at T0: A = tableau entry (level i, column j), error = |A - cp| / cp, estimate = e_ij / cp "
            "(max of the change from the parent and the floor; nan for j = 0), floor = r_i / cp; h in K");
        for (std::size_t i = 0; i < levels; ++i)
            for (std::size_t j = 0; j <= i; ++j) {
                std::optional<double> estimate;
                if (j > 0) estimate = std::max(std::abs(A[i][j] - A[i - 1][j - 1]), floors[i]) / cp;
                out << i << ',' << j << ',' << cell(hs[i]) << ',' << cell(A[i][j]) << ',' << cell(std::abs(A[i][j] - cp) / cp)
                    << ',' << cell(estimate) << ',' << cell(floors[i] / cp) << '\n';
            }

        // The .tex bodies: the levels Ridders used, as a triangular table; the returned entry in the accent colour.
        auto const flag = [&](std::size_t i, std::size_t j, std::string const &text) {
            return i == best->first && j == best->second ? "\\textcolor{accent}{\\textbf{" + text + "}}" : text;
        };
        {
            auto tab = table(o, "ridders-tableau",
                "columns: level i, step h_i in K, A_{i,0} ... A_{i,i} (" + std::to_string(used)
                    + " columns); the entry Ridders returned is in the accent colour. Ridders' own stop after level "
                    + std::to_string(used - 1) + ".");
            for (std::size_t i = 0; i < used; ++i) {
                tab << i << " & " << sig(hs[i], 4);
                for (std::size_t j = 0; j < used; ++j) tab << " & " << (j <= i ? flag(i, j, fixed(A[i][j], 9)) : "");
                tab << " \\\\\n";
            }
        }
        {
            auto tab = table(o, "ridders-tableau-errors",
                "columns: level i, step h_i in K, relative error |A_{i,j} - cp| / cp for j = 0 ... i (" + std::to_string(used)
                    + " columns), then the relative floor r_i / cp; the entry Ridders returned is in the accent colour.");
            for (std::size_t i = 0; i < used; ++i) {
                tab << i << " & " << sig(hs[i], 4);
                for (std::size_t j = 0; j < used; ++j)
                    tab << " & " << (j <= i ? flag(i, j, num(std::abs(A[i][j] - cp) / cp)) : "");
                tab << " & " << num(floors[i] / cp) << " \\\\\n";
            }
        }
    }

