    void ds4_step_scale(Output &o)
    {
        // A narrow feature at a large |x|: tanh((x - x0) / w) at x0 + 0.2, where f varies on the scale w, not |x|.
        double const x0 = 1000.0;
        double const w = 0.5;
        double const x = x0 + 0.2;
        auto const f = [x0, w](double t) { return std::tanh((t - x0) / w); };
        double const th = std::tanh((x - x0) / w);
        double const exact = (1 - th * th) / w;
        auto out = csv(o, "step-scale", "h,error", "Central<2> on tanh((x - 1000) / 0.5) at x = 1000.2, N = 1, relative error");
        Minimum best;
        for (double const h : steps(1, -12)) {
            auto const e = rel_error(derivative<Central<2>>(f, x, h), exact);
            best.offer(h, e);
            out << cell(h) << ',' << cell(e) << '\n';
        }
        double const cbrt_eps = nxx::math::root_epsilon<3, double>();
        value(o, "ScaleDefaultStep", sig(cbrt_eps * x));
        value(o, "ScaleDefaultRelError", sig(*rel_error(derivative<Central<2>>(f, x), exact)));
        value(o, "ScaleFitStep", sig(cbrt_eps * w));
        value(o, "ScaleFitRelError", sig(*rel_error(derivative<Central<2>>(f, x, cbrt_eps * w), exact)));
        value(o, "ScaleBestStep", sig(best.h));
        value(o, "ScaleBestRelError", sig(best.error));
        // The model optimum h* = (S eps |f| / (P C |f'''|))^(1/3) with S = 1, P = 2, C = 1/6, as a check that
        // eps^(1/3) w is within a factor 1.1 of it (PLAN.md DS4).
        double const s2 = 1 - th * th;
        double const f3 = std::abs(-2 * s2 * (s2 - 2 * th * th)) / (w * w * w);
        value(o, "ScaleModelBestStep", sig(std::cbrt(dbl_eps * std::abs(th) / (2.0 / 6 * f3))));
        int calls = 0;
        auto const r = derivative<Ridders>(Counted{ f, &calls }, x, w / 4);
        ridders_values(o, "ScaleRiddersUser", r, exact, calls);
        value(o, "ScaleRiddersUserStep", sig(w / 4));
        calls = 0;
        auto const rd = derivative<Ridders>(Counted{ f, &calls }, x);
        ridders_values(o, "ScaleRiddersDefault", rd, exact, calls);
    }

