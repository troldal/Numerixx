// Generates every number and every data set the book quotes, by running Numerixx itself: data/values.tex (one
// \val... macro per number quoted in the text) and data/<figure>.csv (one file per plotted data set). Run through
// the CMake target numerixx_book_data, which passes the data/ directory. Never edit the outputs by hand.
//
// To add a data set: write a function below that computes it with the library and writes it with the helpers, call
// it from main, and document in data/README.md which figure or chapter uses it. Reference values come from closed
// forms or independent sources, as in the tests, never from Numerixx itself.

#include <numerixx/deriv.hpp>

#include <cmath>
#include <cstdio>
#include <filesystem>
#include <fstream>
#include <string>
#include <string_view>

namespace {

    constexpr std::string_view header = "Generated by tools/generate_data.cpp -- do not edit";

    // A CSV file with a header line of column names (pgfplots reads it with \addplot table[col sep=comma]).
    std::ofstream csv(std::filesystem::path const &dir, std::string_view name, std::string_view columns)
    {
        std::ofstream out(dir / (std::string(name) + ".csv"));
        out << "# " << header << '\n' << columns << '\n';
        out.precision(17);
        return out;
    }

    // One \val<name> macro in values.tex; name is letters only (a LaTeX command name).
    void value(std::ofstream &tex, std::string_view name, std::string_view text)
    { tex << "\\newcommand{\\val" << name << "}{" << text << "}\n"; }

    std::string scientific(double v, int digits = 2)
    {
        char buf[64];
        std::snprintf(buf, sizeof buf, "%.*e", digits - 1, v);
        return buf;
    }

    // TEMPLATE data set, used by the layout test: the error of Central<2> for d/dx exp(x) at x = 1 against the step
    // h = 10^-k. Replace or remove it when the real figures exist.
    void template_step_error(std::filesystem::path const &dir, std::ofstream &tex)
    {
        auto out = csv(dir, "template-step-error", "h,error");
        auto const f = [](double x) { return std::exp(x); };
        double const exact = std::exp(1.0);
        for (int k = 1; k <= 13; ++k) {
            double const h = std::pow(10.0, -k);
            if (auto const d = nxx::deriv::derivative(f, 1.0, h)) out << h << ',' << std::abs(d->value - exact) << '\n';
        }
        auto const d = nxx::deriv::derivative(f, 1.0);
        value(tex, "TemplateDefaultError", scientific(std::abs(d->value - exact) / exact));
    }

} // namespace

int main(int argc, char **argv)
{
    if (argc != 2) {
        std::fprintf(stderr, "usage: numerixx_book_generator <data directory>\n");
        return 2;
    }
    std::filesystem::path const dir = argv[1];
    std::filesystem::create_directories(dir);
    std::ofstream tex(dir / "values.tex");
    tex << "% " << header << '\n';
    template_step_error(dir, tex);
    return 0;
}
