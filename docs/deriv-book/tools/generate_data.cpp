    template<int N>
    Statistics ds9_coverage_order(Output &o)
    {
        Statistics st;
        auto out = csv(o, "ridders-coverage-N" + std::to_string(N),
            "fn,name,x,exact,actual,estimate,rel_actual,rel_estimate,evaluations,restarted",
            "Ridders, N = " + std::to_string(N) + ", default initial step; seed " + std::to_string(seed)
                + " (std::mt19937 seeded with seed + fn, x = 0.2 + 2.8 * u32 / 2^32, " + std::to_string(points_per_function)
                + " points per function, the same points for every N); actual = |value - exact|, "
                  "estimate = abs_error; rel_* divided by |exact|; restarted = 1 if a tableau was restarted");
        // The points the scatter plot F14 draws: every plot_every-th case, with the two columns it needs. pgfplots keeps
        // a record of about 480 words of TeX's memory per plotted point, and 5400 points took 2.6 of the 5 million
        // words, so the book did not build; 1800 points are visually the same cloud. Every case enters the statistics
        // and the full files. An actual error of exactly 0 is clipped here to eps |exact|, so that it can sit on a
        // log axis.
        auto plot = csv(o, "ridders-coverage-plot-N" + std::to_string(N), "actual,estimate",
            "the scatter of F14 for N = " + std::to_string(N) + ": every " + std::to_string(plot_every)
                + "rd case of ridders-coverage-N" + std::to_string(N) + ".csv (a TeX memory limit, not a selection), "
                  "actual = |value - exact| clipped to eps |exact| where it is exactly 0, estimate = abs_error");
        for (std::size_t f = 0; f < std::size(study); ++f) {
            std::mt19937 gen(seed + static_cast<std::uint32_t>(f));
            for (int k = 0; k < points_per_function; ++k) {
                double const x = 0.2 + 2.8 * (static_cast<double>(gen()) / 4294967296.0);
                double const exact = study[f].exact(N, x);
                Log log;
                auto const r = derivative<Ridders, N>(Logged{ study[f].fn, &log }, x);
                ++st.cases;
                if (!r || !r->abs_error) {
                    ++st.failed;
                    out << f << ',' << study[f].name << ',' << cell(x) << ',' << cell(exact) << ",nan,nan,nan,nan,"
                        << log.xs.size() << ",nan\n";
                    continue;
                }
                double const actual = std::abs(r->value - exact);
                double const estimate = *r->abs_error;
                bool const was_restarted = restarted(log, N, x);
                st.covered += actual <= estimate ? 1 : 0;
                st.exact += actual == 0 ? 1 : 0;
                st.restarts += was_restarted ? 1 : 0;
                double const ratio = estimate > 0 ? actual / estimate : (actual == 0 ? 0 : std::numeric_limits<double>::infinity());
                st.ratios.push_back(ratio);
                st.worst_ratio = std::max(st.worst_ratio, ratio);
                st.evaluations.push_back(static_cast<double>(log.xs.size()));
                out << f << ',' << study[f].name << ',' << cell(x) << ',' << cell(exact) << ',' << cell(actual) << ','
                    << cell(estimate) << ',' << cell(actual / std::abs(exact)) << ',' << cell(estimate / std::abs(exact)) << ','
                    << log.xs.size() << ',' << (was_restarted ? 1 : 0) << '\n';
                if ((st.cases - 1) % plot_every == 0) {
                    plot << cell(actual == 0 ? dbl_eps * std::abs(exact) : actual) << ',' << cell(estimate) << '\n';
                    ++st.plotted;
                }
            }
        }
        return st;
    }

