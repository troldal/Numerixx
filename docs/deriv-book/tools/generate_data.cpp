    void ds10_ridders_edge(Output &o)
    {
        auto out = csv(o, "ridders-edge", "k,x,ok,covered,rel_error,rel_estimate,evaluations",
            "log x at x = 2^-k, Ridders with the default initial step; the last row is x = 0.01 (E10), k = log2(1/x); "
            "ok = 1 if a value was returned, covered = 1 if its error is within the estimate");
        auto const log_fn = [](double x) { return std::log(x); };
        // Three readings of "how close to the edge": the smallest x that still returns a value (the level budget runs
        // out below it), the smallest x whose result still has ten correct digits (relative error below 1e-10), and
        // the first x at which the budget of 64 evaluations is exhausted.
        std::optional<int> limit_k;
        std::optional<int> ten_digits_k;
        std::optional<int> cap_k;
        auto const row = [&](double k, double x) {
            int calls = 0;
            auto const r = derivative<Ridders>(Counted{ log_fn, &calls }, x);
            double const exact = 1 / x;
            auto const e = rel_error(r, exact);
            bool const covered = r && e && std::abs(r->value - exact) <= *r->abs_error;
            out << cell(k) << ',' << cell(x) << ',' << (r ? 1 : 0) << ',' << (covered ? 1 : 0) << ',' << cell(e) << ','
                << cell(r ? std::optional<double>(*r->abs_error / exact) : std::nullopt) << ',' << calls << '\n';
            return std::make_tuple(r.has_value(), covered, e, calls, r);
        };
        for (int k = 2; k <= 40; ++k) {
            double const x = std::ldexp(1.0, -k);
            auto const [ok, covered, e, calls, r] = row(k, x);
            if (ok) limit_k = k;
            if (ok && covered && e && *e < 1e-10) ten_digits_k = k;
            if (!cap_k && calls >= 2 * nxx::deriv::detail::ridders_levels) cap_k = k;
        }
        auto const [ok, covered, e, calls, r] = row(std::log2(1 / 0.01), 0.01);
        if (limit_k && ten_digits_k && cap_k) {
            value(o, "RiddersEdgeLimit", sig(std::ldexp(1.0, -*limit_k)));
            value(o, "RiddersEdgeLimitExponent", integer(*limit_k));
            value(o, "RiddersEdgeTenDigits", sig(std::ldexp(1.0, -*ten_digits_k)));
            value(o, "RiddersEdgeTenDigitsExponent", integer(*ten_digits_k));
            value(o, "RiddersEdgeCapExponent", integer(*cap_k));
        } else {
            o.fail("DS10: the edge limits were not all found");
        }
        ridders_values(o, "RiddersEdgeAtOneHundredth", r, 100.0, calls);
        value(o, "RiddersEdgeEvalsAtOneHundredth", integer(calls));
        auto const d = derivative<Central<2>>(log_fn, 0.01);
        value(o, "EdgeCentralAtOneHundredthRelError", sig(*rel_error(d, 100.0)));
    }

