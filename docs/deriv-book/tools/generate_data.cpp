    void ds18_examples(Output &o)
    {
        // E13: an Arrhenius rate k(T) = A exp(-Ea / (R T)) with illustrative parameters (data/README.md lists them;
        // the example must use the same): A = 1e10 1/s, Ea = 80 kJ/mol, T = 600 K, R = 8.31446261815324 J/(mol K).
        double const A = 1e10;
        double const Ea = 80000.0;
        double const R = 8.31446261815324;
        double const T = 600.0;
        double const k0 = A * std::exp(-Ea / (R * T));
        auto const rate_T = [A, Ea, R](double t) { return A * std::exp(-Ea / (R * t)); };
        auto const rate_Ea = [A, R, T](double ea) { return A * std::exp(-ea / (R * T)); };
        auto const rate_A = [Ea, R, T](double a) { return a * std::exp(-Ea / (R * T)); };
        int calls = 0;
        auto const dT = derivative<Ridders>(Counted{ rate_T, &calls }, T);
        ridders_values(o, "SensitivityRate", dT, k0 * Ea / (R * T * T), calls);
        calls = 0;
        auto const dEa = derivative<Ridders>(Counted{ rate_Ea, &calls }, Ea);
        ridders_values(o, "SensitivityEa", dEa, -k0 / (R * T), calls);
        value(o, "SensitivityK", sig(k0, 4));
        if (dEa) {
            double const scaled = Ea / k0 * dEa->value;
            value(o, "SensitivityScaled", sig(scaled, 4));
            value(o, "SensitivityScaledExact", sig(-Ea / (R * T), 4));
            value(o, "SensitivityScaledRelError", sig(std::abs(scaled + Ea / (R * T)) / (Ea / (R * T))));
        }
        // The Jacobian loop over (A, Ea): one Ridders call per column, evaluations summed.
        calls = 0;
        auto const dA = derivative<Ridders>(Counted{ rate_A, &calls }, A);
        int const calls_A = calls;
        auto const dEa2 = derivative<Ridders>(Counted{ rate_Ea, &calls }, Ea);
        value(o, "JacobianEvals", integer(calls));
        value(o, "JacobianEvalsA", integer(calls_A));
        value(o, "JacobianEvalsEa", integer(calls - calls_A));
        if (dA) value(o, "JacobianARelError", sig(*rel_error(dA, std::exp(-Ea / (R * T)))));
        if (dEa2) value(o, "JacobianEaRelError", sig(*rel_error(dEa2, -k0 / (R * T))));

        // E14: cpp_bin_float_50, exp at 1 with Central<6> and Ridders.
#ifdef NUMERIXX_BOOK_HAVE_BOOST
        auto const exp_mp = [](mp50 const &x) { return mp50(boost::multiprecision::exp(x)); };
        mp50 const e_mp = boost::multiprecision::exp(mp50(1));
        auto const c6 = derivative<Central<6>>(exp_mp, mp50(1));
        value(o, "MpCentralSixRelError", sig(*rel_error_t(c6, e_mp)));
        value(o, "MpCentralSixStep", sig(static_cast<double>(nxx::math::root_epsilon<7, mp50>())));
        calls = 0;
        auto const r = derivative<Ridders>(Counted{ exp_mp, &calls }, mp50(1));
        if (r && r->abs_error) {
            mp50 const actual = mp50(nxx::math::abs(mp50(r->value - e_mp)));
            value(o, "MpRiddersRelError", sig(static_cast<double>(mp50(actual / e_mp))));
            value(o, "MpRiddersEstimate", sig(static_cast<double>(*r->abs_error)));
            value(o, "MpRiddersRelEstimate", sig(static_cast<double>(mp50(*r->abs_error / e_mp))));
            value(o, "MpRiddersEvals", integer(calls));
        } else {
            o.fail("DS18: Ridders on cpp_bin_float_50 failed");
        }
        auto const c2 = derivative<Central<2>>(exp_mp, mp50(1));
        value(o, "MpCentralTwoRelError", sig(*rel_error_t(c2, e_mp)));
#endif
    }

