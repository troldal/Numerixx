    // The nine functions of the random study with their derivatives of order 1 to 4 in closed form.
    double falling(double a, int n)
    {
        double r = 1;
        for (int i = 0; i < n; ++i) r *= a - i;
        return r;
    }

    long long factorial(int n) { return n <= 1 ? 1 : n * factorial(n - 1); }

    // Powers are formed by multiplication (ipow), never by libm's pow, so that the references are reproducible.
    double sin_n(int n, double x) { return std::sin(x + n * std::numbers::pi / 2); }
    double log_n(int n, double x) { return (n % 2 == 1 ? 1 : -1) * static_cast<double>(factorial(n - 1)) / ipow(x, n); }
    double sqrt_n(int n, double x) { return falling(0.5, n) * std::sqrt(x) / ipow(x, n); }
    double inverse_n(int n, double x) { return (n % 2 == 0 ? 1 : -1) * static_cast<double>(factorial(n)) / ipow(x, n + 1); }
    // 1/(1 + 25 x^2) = Re 1/(1 + 5ix), whose n-th derivative is (-1)^n n! (5i)^n (1 + 5ix)^-(n+1); (5i)^n is exact.
    double runge_n(int n, double x)
    {
        std::complex<double> const z(1.0, 5.0 * x);
        std::complex<double> zn(1.0, 0.0);
        for (int i = 0; i <= n; ++i) zn *= z;
        std::complex<double> c(static_cast<double>(factorial(n)), 0.0);
        for (int i = 0; i < n; ++i) c *= std::complex<double>(0.0, 5.0);
        return ((n % 2 == 0 ? c : -c) / zn).real();
    }
    double quintic_n(int n, double x) { return falling(5, n) * ipow(x, 5 - n); }
    // d^n/dx^n exp(-x^2) = (-1)^n H_n(x) exp(-x^2), with the physicists' Hermite polynomials.
    double gauss_n(int n, double x)
    {
        double const g = std::exp(-x * x);
        switch (n) {
            case 1: return -(2 * x) * g;
            case 2: return (4 * x * x - 2) * g;
            case 3: return -(8 * x * x * x - 12 * x) * g;
            default: return (16 * x * x * x * x - 48 * x * x + 12) * g;
        }
    }
    // With t = tanh x and s = 1 - t^2: t' = s, t'' = -2ts, t''' = s(6t^2 - 2), t'''' = 8ts(2 - 3t^2).
    double tanh_n(int n, double x)
    {
        double const t = std::tanh(x);
        double const s = 1 - t * t;
        switch (n) {
            case 1: return s;
            case 2: return -2 * t * s;
            case 3: return s * (6 * t * t - 2);
            default: return 8 * t * s * (2 - 3 * t * t);
        }
    }

    struct StudyFunction
    {
        char const *name;
        double (*fn)(double);
        double (*exact)(int, double);
    };

    constexpr StudyFunction study[] = {
        { "exp", [](double x) { return std::exp(x); }, [](int, double x) { return std::exp(x); } },
        { "sin", [](double x) { return std::sin(x); }, sin_n },
        { "log", [](double x) { return std::log(x); }, log_n },
        { "sqrt", [](double x) { return std::sqrt(x); }, sqrt_n },
        { "inverse", [](double x) { return 1 / x; }, inverse_n },
        { "runge", [](double x) { return 1 / (1 + 25 * x * x); }, runge_n },
        { "quintic", [](double x) { return x * x * x * x * x; }, quintic_n },
        { "gauss", [](double x) { return std::exp(-x * x); }, gauss_n },
        { "tanh", [](double x) { return std::tanh(x); }, tanh_n },
    };
    constexpr int points_per_function = 300;
    constexpr int plot_every = 3; // the scatter F14 draws every third case (TeX's memory, see ds9_coverage_order)

    // The functions' names as the text writes them, in the order of `study` (for the macros that name functions).
    constexpr char const *const study_latex[] = {
        "$\\mathrm{e}^x$", "$\\sin x$", "$\\log x$", "$\\sqrt{x}$", "$1/x$", "the Runge function", "$x^5$",
        "$\\mathrm{e}^{-x^2}$", "$\\tanh x$",
    };

    // One case of the random study, kept so that the summary can look at subsets (the histogram's tail, the
    // zero-error cases, the uncovered cases).
    struct Case
    {
        std::size_t fn;
        double x;
        double evaluations;
        bool covered;
        bool zero;
        bool restarted;
    };

    struct Statistics
    {
        int cases = 0;
        int covered = 0;
        int exact = 0;
        int restarts = 0;
        int failed = 0;
        int plotted = 0;
        double worst_ratio = 0;
        std::vector<double> ratios;
        std::vector<double> evaluations;
        std::vector<double> rel_errors; // |value - exact| / |exact|
        std::vector<Case> records;
    };

    // The random study's points for function f: 300 draws from std::mt19937 seeded with seed + f, the same for every
    // order and every method.
    std::vector<double> study_points(std::size_t f)
    {
        std::mt19937 gen(seed + static_cast<std::uint32_t>(f));
        std::vector<double> xs;
        for (int k = 0; k < points_per_function; ++k) xs.push_back(0.2 + 2.8 * (static_cast<double>(gen()) / 4294967296.0));
        return xs;
    }

    // The evaluation counts of a study, sorted.
    std::vector<double> sorted_evaluations(Statistics const &st)
    {
        std::vector<double> ev = st.evaluations;
        std::sort(ev.begin(), ev.end());
        return ev;
    }

    // Coverage in percent to one decimal, as the style decision says, except where one decimal would read 100.0
    // while a case is uncovered: then two (R1-numerics-17e).
    // A worst ratio of error to estimate: two significant digits, but more where two would print 1.0 for a ratio above
    // 1, an uncovered case that "1.0" would hide (R3-evidence-08).
    std::string ratio_text(double r)
    {
        std::string s = sig(r);
        for (int d = 3; r > 1 && std::stod(s) <= 1 && d <= 6; ++d) s = sig(r, d);
        return s;
    }

    std::string coverage_percent(int covered, int cases)
    {
        std::string const s = percent(static_cast<double>(covered) / cases);
        return s == "100.0" && covered < cases ? fixed(100.0 * covered / cases, 2) : s;
    }

    // The functions of a subset of cases, each with its count, most frequent first: "$1/x$ (69), $\log x$ (46)".
    std::string functions_with_counts(std::vector<Case> const &cases, std::size_t skip = std::size(study))
    {
        std::array<int, std::size(study)> count{};
        for (Case const &c : cases) ++count[c.fn];
        std::vector<std::size_t> order;
        for (std::size_t f = 0; f < std::size(study); ++f)
            if (count[f] > 0 && f != skip) order.push_back(f);
        std::stable_sort(order.begin(), order.end(), [&](std::size_t a, std::size_t b) { return count[a] > count[b]; });
        std::string text;
        for (std::size_t i = 0; i < order.size(); ++i) {
            if (i > 0) text += i + 1 == order.size() ? " and " : ", ";
            text += std::string(study_latex[order[i]]) + " (" + std::to_string(count[order[i]]) + ")";
        }
        return text.empty() ? "none" : text;
    }

    template<int N>
    Statistics ds9_coverage_order(Output &o)
    {
        Statistics st;
        auto out = csv(o, "ridders-coverage-N" + std::to_string(N),
            "fn,name,x,exact,actual,estimate,rel_actual,rel_estimate,evaluations,restarted",
            "Ridders, N = " + std::to_string(N) + ", default initial step; seed " + std::to_string(seed)
                + " (std::mt19937 seeded with seed + fn, x = 0.2 + 2.8 * u32 / 2^32, " + std::to_string(points_per_function)
                + " points per function, the same points for every N); actual = |value - exact|, "
                  "estimate = abs_error; rel_* divided by |exact|; restarted = 1 if a tableau was restarted");
        // The points the scatter plot F14 draws: every plot_every-th case, with the two columns it needs. pgfplots keeps
        // a record of about 480 words of TeX's memory per plotted point, and 5400 points took 2.6 of the 5 million
        // words, so the book did not build; 1800 points are visually the same cloud. Every case enters the statistics
        // and the full files. An actual error of exactly 0 is clipped here to eps |exact|, so that it can sit on a
        // log axis.
        auto plot = csv(o, "ridders-coverage-plot-N" + std::to_string(N), "actual,estimate",
            "the scatter of F14 for N = " + std::to_string(N) + ": every " + std::to_string(plot_every)
                + "rd case of ridders-coverage-N" + std::to_string(N) + ".csv (a TeX memory limit, not a selection), "
                  "actual = |value - exact| clipped to eps |exact| where it is exactly 0, estimate = abs_error");
        for (std::size_t f = 0; f < std::size(study); ++f) {
            for (double const x : study_points(f)) {
                double const exact = study[f].exact(N, x);
                Log log;
                auto const r = derivative<Ridders, N>(Logged{ study[f].fn, &log }, x);
                ++st.cases;
                if (!r || !r->abs_error) {
                    ++st.failed;
                    out << f << ',' << study[f].name << ',' << cell(x) << ',' << cell(exact) << ",nan,nan,nan,nan,"
                        << log.xs.size() << ",nan\n";
                    continue;
                }
                double const actual = std::abs(r->value - exact);
                double const estimate = *r->abs_error;
                bool const was_restarted = restarted(log, N, x);
                st.covered += actual <= estimate ? 1 : 0;
                st.exact += actual == 0 ? 1 : 0;
                st.restarts += was_restarted ? 1 : 0;
                double const ratio = estimate > 0 ? actual / estimate : (actual == 0 ? 0 : std::numeric_limits<double>::infinity());
                st.ratios.push_back(ratio);
                st.worst_ratio = std::max(st.worst_ratio, ratio);
                st.evaluations.push_back(static_cast<double>(log.xs.size()));
                st.rel_errors.push_back(actual / std::abs(exact));
                st.records.push_back({ f, x, static_cast<double>(log.xs.size()), actual <= estimate, actual == 0, was_restarted });
                out << f << ',' << study[f].name << ',' << cell(x) << ',' << cell(exact) << ',' << cell(actual) << ','
                    << cell(estimate) << ',' << cell(actual / std::abs(exact)) << ',' << cell(estimate / std::abs(exact)) << ','
                    << log.xs.size() << ',' << (was_restarted ? 1 : 0) << '\n';
                if ((st.cases - 1) % plot_every == 0) {
                    plot << cell(actual == 0 ? dbl_eps * std::abs(exact) : actual) << ',' << cell(estimate) << '\n';
                    ++st.plotted;
                }
            }
        }
        return st;
    }

    // The uncovered cases of a study: the function that holds most of them, its count and range of x, and the others
    // (R1-numerics-12). Written only where a case is uncovered.
    void uncovered_values(Output &o, Statistics const &st, std::string const &method, std::string const &suffix)
    {
        std::vector<Case> uncovered;
        for (Case const &c : st.records)
            if (!c.covered) uncovered.push_back(c);
        if (uncovered.empty()) return;
        std::array<int, std::size(study)> count{};
        for (Case const &c : uncovered) ++count[c.fn];
        std::size_t const main_fn = static_cast<std::size_t>(std::max_element(count.begin(), count.end()) - count.begin());
        double x_min = std::numeric_limits<double>::infinity();
        double x_max = 0;
        for (Case const &c : uncovered)
            if (c.fn == main_fn) {
                x_min = std::min(x_min, c.x);
                x_max = std::max(x_max, c.x);
            }
        value(o, method + "UncoveredMainFunction" + suffix, study_latex[main_fn]);
        value(o, method + "UncoveredMainCount" + suffix, integer(count[main_fn]));
        value(o, method + "UncoveredMainMinX" + suffix, sig(x_min));
        value(o, method + "UncoveredMainMaxX" + suffix, sig(x_max));
        value(o, method + "UncoveredOthers" + suffix, functions_with_counts(uncovered, main_fn));
    }

    std::array<Statistics, 5> ds9_ridders_coverage(Output &o)
    {
        std::array<Statistics, 5> all{};
        char const *const names[] = { "", "First", "Second", "Third", "Fourth" };
        for_each(derivative_orders{}, [&](auto n) {
            constexpr int N = decltype(n)::value;
            Statistics const st = ds9_coverage_order<N>(o);
            all[N] = st;
            std::string const suffix = names[N];
            value(o, "RiddersCoverage" + suffix, coverage_percent(st.covered, st.cases));
            value(o, "RiddersUncovered" + suffix, integer(st.cases - st.covered));
            value(o, "RiddersMedianRatio" + suffix, sig(median(st.ratios)));
            value(o, "RiddersWorstRatio" + suffix, ratio_text(st.worst_ratio));
            std::vector<double> ev = st.evaluations;
            std::sort(ev.begin(), ev.end());
            double const median_evals = ev[ev.size() / 2];
            value(o, "RiddersEvalsMin" + suffix, integer(static_cast<long long>(ev.front())));
            value(o, "RiddersEvalsMedian" + suffix, integer(static_cast<long long>(median_evals)));
            value(o, "RiddersEvalsMax" + suffix, integer(static_cast<long long>(ev.back())));
            value(o, "RiddersZeroError" + suffix, integer(st.exact));
            value(o, "RiddersRestarted" + suffix, integer(st.restarts));
            value(o, "RiddersFailed" + suffix, integer(st.failed));

            // The tail of the evaluation histogram: the cases above the median count, with the restarts among them
            // and the functions they come from (R1-numerics-02, R1-evidence-02).
            std::vector<Case> tail;
            for (Case const &c : st.records)
                if (c.evaluations > median_evals) tail.push_back(c);
            double tail_min = ev.back();
            int tail_restarts = 0;
            for (Case const &c : tail) {
                tail_min = std::min(tail_min, c.evaluations);
                tail_restarts += c.restarted ? 1 : 0;
            }
            value(o, "RiddersTailCases" + suffix, integer(static_cast<long long>(tail.size())));
            value(o, "RiddersTailMinEvals" + suffix, integer(static_cast<long long>(tail.empty() ? 0 : tail_min)));
            value(o, "RiddersTailRestarts" + suffix, integer(tail_restarts));
            value(o, "RiddersTailFunctions" + suffix, functions_with_counts(tail));

            // The cases with an actual error of exactly 0: how many on x^5, over how many functions
            // (R1-numerics-03, R1-evidence-04). They are bit-exact results, not observed exact stops.
            std::vector<Case> zero;
            for (Case const &c : st.records)
                if (c.zero) zero.push_back(c);
            int on_quintic = 0;
            std::array<bool, std::size(study)> seen{};
            for (Case const &c : zero) {
                on_quintic += study[c.fn].name == std::string_view("quintic") ? 1 : 0;
                seen[c.fn] = true;
            }
            value(o, "RiddersZeroOnQuintic" + suffix, integer(on_quintic));
            value(o, "RiddersZeroFunctions" + suffix, integer(static_cast<long long>(std::count(seen.begin(), seen.end(), true))));

            uncovered_values(o, st, "Ridders", suffix);
            // The median relative error, for the comparison with the one-sided form (Phase 5).
            value(o, "RiddersMedianRelError" + suffix, sig(median(st.rel_errors)));
        });
        // A smaller initial step usually restores the margin (R2-numerics-03): every uncovered case of the study,
        // all four orders, rerun with a quarter and a sixty-fourth of the default initial step (max(|x|, 1) over
        // the library's divisor for the order), and how many of them are then covered. Sidebar 6.2 quotes the
        // three counts.
        int margin_cases = 0, quarter_covered = 0, sixty_fourth_covered = 0;
        for_each(derivative_orders{}, [&](auto n) {
            constexpr int N = decltype(n)::value;
            double const divisor = static_cast<double>(nxx::deriv::detail::ridders_divisors[static_cast<std::size_t>(N - 1)]);
            for (Case const &c : all[N].records) {
                if (c.covered) continue;
                ++margin_cases;
                double const exact = study[c.fn].exact(N, c.x);
                double const h0 = std::max(std::abs(c.x), 1.0) / divisor;
                auto const covered_at = [&](double h) {
                    auto const r = derivative<Ridders, N>(study[c.fn].fn, c.x, h);
                    return r && r->abs_error && std::abs(r->value - exact) <= *r->abs_error;
                };
                quarter_covered += covered_at(h0 / 4) ? 1 : 0;
                sixty_fourth_covered += covered_at(h0 / 64) ? 1 : 0;
            }
        });
        value(o, "RiddersMarginCases", integer(margin_cases));
        value(o, "RiddersMarginQuarterCovered", integer(quarter_covered));
        value(o, "RiddersMarginSixtyFourthCovered", integer(sixty_fourth_covered));
        value(o, "RiddersCases", integer(all[1].cases));
        value(o, "RiddersPlotEvery", integer(plot_every));
        value(o, "RiddersPlotCases", integer(all[1].plotted));
        value(o, "RiddersFunctions", integer(static_cast<long long>(std::size(study))));
        value(o, "RiddersPointsPerFunction", integer(points_per_function));
        return all;
    }

    // DS9, one-sided (Phase 5): ForwardRidders on the same nine functions at the same 300 points, N = 1 to 4, double,
    // default initial step max(|x|, 1) / 32. Macros only (no per-case file, no figure). Restarts are not counted: the
    // functions are finite above every x of the study, so a restart could only follow an untrusted result, which the
    // call log cannot show (see restarted()).
    template<int N>
    Statistics ds9_forward_order()
    {
        Statistics st;
        for (std::size_t f = 0; f < std::size(study); ++f) {
            for (double const x : study_points(f)) {
                double const exact = study[f].exact(N, x);
                int calls = 0;
                auto const r = derivative<ForwardRidders, N>(Counted{ study[f].fn, &calls }, x);
                ++st.cases;
                if (!r || !r->abs_error) {
                    ++st.failed;
                    continue;
                }
                double const actual = std::abs(r->value - exact);
                double const estimate = *r->abs_error;
                st.covered += actual <= estimate ? 1 : 0;
                st.exact += actual == 0 ? 1 : 0;
                double const ratio = estimate > 0 ? actual / estimate : (actual == 0 ? 0 : std::numeric_limits<double>::infinity());
                st.ratios.push_back(ratio);
                st.worst_ratio = std::max(st.worst_ratio, ratio);
                st.evaluations.push_back(static_cast<double>(calls));
                st.rel_errors.push_back(actual / std::abs(exact));
                st.records.push_back({ f, x, static_cast<double>(calls), actual <= estimate, actual == 0, false });
            }
        }
        return st;
    }

    std::array<Statistics, 5> ds9_forward_ridders(Output &o, std::array<Statistics, 5> const &central)
    {
        std::array<Statistics, 5> all{};
        char const *const names[] = { "", "First", "Second", "Third", "Fourth" };
        for_each(derivative_orders{}, [&](auto n) {
            constexpr int N = decltype(n)::value;
            Statistics const st = ds9_forward_order<N>();
            all[N] = st;
            std::string const suffix = names[N];
            value(o, "ForwardRiddersCoverage" + suffix, coverage_percent(st.covered, st.cases));
            value(o, "ForwardRiddersUncovered" + suffix, integer(st.cases - st.covered));
            value(o, "ForwardRiddersMedianRatio" + suffix, sig(median(st.ratios)));
            value(o, "ForwardRiddersWorstRatio" + suffix, ratio_text(st.worst_ratio));
            std::vector<double> const ev = sorted_evaluations(st);
            value(o, "ForwardRiddersEvalsMin" + suffix, integer(static_cast<long long>(ev.front())));
            value(o, "ForwardRiddersEvalsMedian" + suffix, integer(static_cast<long long>(ev[ev.size() / 2])));
            value(o, "ForwardRiddersEvalsMax" + suffix, integer(static_cast<long long>(ev.back())));
            value(o, "ForwardRiddersZeroError" + suffix, integer(st.exact));
            value(o, "ForwardRiddersFailed" + suffix, integer(st.failed));
            double const median_error = median(st.rel_errors);
            value(o, "ForwardRiddersMedianRelError" + suffix, sig(median_error));
            // How much less accurate than Ridders on the same cases: the ratio of the two median relative errors.
            value(o, "ForwardRiddersAccuracyFactor" + suffix, sig(median_error / median(central[N].rel_errors)));
            uncovered_values(o, st, "ForwardRidders", suffix);
        });
        // The extremes over the four orders, so that a sentence that quotes a range stays true after a regeneration
        // (6.7): the lowest and highest coverage and the largest worst ratio.
        std::size_t low = 1;
        std::size_t high = 1;
        double worst = 0;
        for (std::size_t N = 1; N <= 4; ++N) {
            if (all[N].covered * all[low].cases < all[low].covered * all[N].cases) low = N;
            if (all[N].covered * all[high].cases > all[high].covered * all[N].cases) high = N;
            worst = std::max(worst, all[N].worst_ratio);
        }
        value(o, "ForwardRiddersCoverageMin", coverage_percent(all[low].covered, all[low].cases));
        value(o, "ForwardRiddersCoverageMax", coverage_percent(all[high].covered, all[high].cases));
        value(o, "ForwardRiddersWorstRatioMax", ratio_text(worst));
        return all;
    }

