// Generates every number and every data set the book quotes, by running Numerixx itself: data/values.tex (one
// \val... macro per number quoted in the text), data/<figure>.csv (one file per plotted data set) and
// data/table-<name>.tex (the body rows of a tabular, read with \input). Run through the CMake target
// numerixx_book_data, which passes the data/ directory. Never edit the outputs by hand.
//
// The data sets are those of PLAN.md sections 4.3 and 4.4 (DS1 to DS23, E6, E22, E24 and the Phase 5 additions of
// 4.4), in its conventions: double unless stated; steps h = 10^(k/4)
// (four per decade); a result that is not finite is written as "nan" (pgfplots skips it); every reference value comes
// from a closed form coded here or in the shared headers in code/ (the Shomate derivatives, exp, the closed forms of
// tests/test_orders.cpp), never from Numerixx; the random study uses std::mt19937 with the fixed seed written into the
// CSV header, and draws its points from the raw 32-bit output so that every standard library gives the same points;
// the float fourth derivative is computed inside the same pragma the tests use, since this file builds with warnings
// as errors; the weight tables are read through nxx::deriv::detail::make_table (decision A3) and checked against the
// moment conditions before they are written, so a table in the book is self-verified.
//
// Formatting (PLAN.md section 8, item 3): errors, estimates and steps to two significant digits, coverage to one
// decimal in percent, counts as integers; \val macros hold raw numbers for \num and \SI. Macro names are letters only.
// Naming: <X>RelError = |value - exact| / |exact|; <X>Actual = |value - exact|; <X>Estimate = abs_error as returned
// (absolute, in the derivative's unit); <X>RelEstimate = abs_error / |exact|; <X>Evals = evaluations of fn.
//
// To add a data set: write a function below that computes it with the library and writes it with the helpers, call
// it from main, and document in data/README.md which figure or chapter uses it. The generator returns 1 if a
// self-check fails (a moment condition, the nitrogen function against its verified values, Ridders' returned entry not
// found in the tableau), so that the CMake target fails loudly.

