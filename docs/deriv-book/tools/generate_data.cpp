    void ds13_default_steps(Output &o)
    {
        auto tab = table(o, "default-steps",
            "columns: family, P, N, exponent 1/(P+N), default step for double at |x| <= 1 (root_epsilon), model error "
            "eps^(P/(P+N)) for double, evaluations of fn");
        auto const row = [&]<typename Family, int P, int N>(std::string const &name, std::integral_constant<int, P>,
                             std::integral_constant<int, N>) {
            constexpr int exponent = P + N;
            double const step = nxx::math::root_epsilon<exponent, double>();
            double const model = std::pow(dbl_eps, static_cast<double>(P) / exponent);
            constexpr std::size_t evaluations = nxx::deriv::detail::make_table<N>(Family{}).nodes.size();
            tab << "\\code{" << name << "<" << P << ">} & " << P << " & " << N << " & $1/" << exponent << "$ & " << num(step)
                << " & " << num(model) << " & " << evaluations << " \\\\\n";
        };
        for_each(derivative_orders{}, [&](auto n) {
            for_each(central_orders{}, [&](auto p) { row.template operator()<Central<decltype(p)::value>>("Central", p, n); });
        });
        for_each(derivative_orders{}, [&](auto n) {
            for_each(one_sided_orders{}, [&](auto p) { row.template operator()<Forward<decltype(p)::value>>("Forward", p, n); });
        });
        // The steps and model errors the text quotes directly.
        value(o, "RootEpsThreeDouble", sig(nxx::math::root_epsilon<3, double>()));
        value(o, "RootEpsFourDouble", sig(nxx::math::root_epsilon<4, double>()));
        value(o, "RootEpsFiveDouble", sig(nxx::math::root_epsilon<5, double>()));
        value(o, "RootEpsSixDouble", sig(nxx::math::root_epsilon<6, double>()));
        value(o, "RootEpsThreeFloat", sig(static_cast<double>(nxx::math::root_epsilon<3, float>())));
        value(o, "ModelCentralTwoFirstDouble", sig(std::pow(dbl_eps, 2.0 / 3)));
        value(o, "ModelCentralTwoSecondDouble", sig(std::pow(dbl_eps, 2.0 / 4)));
        value(o, "ModelCentralTwoThirdDouble", sig(std::pow(dbl_eps, 2.0 / 5)));
        value(o, "ModelCentralTwoFourthDouble", sig(std::pow(dbl_eps, 2.0 / 6)));
        value(o, "ModelCentralTenFirstDouble", sig(std::pow(dbl_eps, 10.0 / 11)));
        double const float_eps = std::numeric_limits<float>::epsilon();
        value(o, "ModelCentralTwoFirstFloat", sig(std::pow(float_eps, 2.0 / 3)));
        value(o, "ModelCentralTwoFourthFloat", sig(std::pow(float_eps, 2.0 / 6)));
        value(o, "ModelForwardOneFirstDouble", sig(std::pow(dbl_eps, 1.0 / 2)));
        value(o, "ModelForwardOneFourthDouble", sig(std::pow(dbl_eps, 1.0 / 5)));
        // The constant the default step drops, for Central<2> and f': (N S / (P C))^(1/(P+N)) = (1 * 1 / (2/6))^(1/3).
        value(o, "StepConstantCentralTwoFirst", sig(std::cbrt(3.0)));
        value(o, "StepConstantCentralTwoSecond", sig(std::pow(2.0 * 4 / (2.0 / 12), 1.0 / 4)));
        value(o, "StepConstantCentralTwoFourth", sig(std::pow(4.0 * 16 / (2.0 / 6), 1.0 / 6)));
        // What dropping the constant costs by the model (Appendix B.4, eq. derivations-cost): at h = h*/k the error
        // is (N k^-P + P k^N) / (P + N) times the minimum, with k = (N S / (P C))^(1/(P+N)) from the rule's table.
        auto const step_cost = [&]<typename Rule, int N>(std::string const &name) {
            constexpr int P = nxx::deriv::detail::make_table<N>(Rule{}).order;
            auto const [S_ampl, C_errc] = rule_constants<Rule, N>();
            double const k = std::pow(N * S_ampl / (P * C_errc), 1.0 / (P + N));
            double const cost = (N * std::pow(k, -P) + P * std::pow(k, N)) / (P + N);
            value(o, "StepCost" + name, sig(cost, 3));
            return k;
        };
        step_cost.template operator()<Central<2>, 1>("CentralTwoFirst");
        step_cost.template operator()<Central<2>, 2>("CentralTwoSecond");
        step_cost.template operator()<Central<2>, 4>("CentralTwoFourth");
        step_cost.template operator()<Central<4>, 4>("CentralFourFourth");
        double const k_ten = step_cost.template operator()<Central<10>, 1>("CentralTenFirst");
        value(o, "StepConstantCentralTenFirst", sig(k_ten));
        // Misjudging the scale by a factor 2 (R1-numerics-06, R1-library-09): a step h*/2 multiplies the rounding
        // term by 2^N and a step 2 h* the truncation term by 2^P; with the two terms in the ratio N : P at the
        // balance, the total error grows by (N 2^-P + P 2^N) / (P + N) or (N 2^P + P 2^-N) / (P + N), whichever
        // is larger.
        auto const misjudge = [&](int P, int N, std::string const &name) {
            double const halved = (N * std::pow(2.0, -P) + P * std::pow(2.0, N)) / (P + N);
            double const doubled = (N * std::pow(2.0, P) + P * std::pow(2.0, -N)) / (P + N);
            value(o, "MisjudgeCost" + name, sig(std::max(halved, doubled)));
        };
        misjudge(2, 1, "CentralTwoFirst");
        misjudge(2, 4, "CentralTwoFourth");
        misjudge(4, 4, "CentralFourFourth");
        // What the next central order would gain by the model's exponent alone: -log10(eps) times
        // (12/13 - 10/11) for f' in digits (R1-numerics-07, R1-evidence-05), and, since a fraction of a digit is
        // not a count the book states, the same gain as a factor in the error, 10 to that power (style
        // decision 24); the constants S and C are left out, as 9.4 says.
        auto const cap_gain = [&](double eps, int N, std::string const &name) {
            double const digits = -std::log10(eps) * (12.0 / (12 + N) - 10.0 / (10 + N));
            value(o, "CapGainCentralTwelve" + name, sig(digits));
            value(o, "CapGainFactorCentralTwelve" + name, sig(std::pow(10.0, digits)));
        };
        cap_gain(dbl_eps, 1, "FirstDouble");
        cap_gain(dbl_eps, 4, "FourthDouble");
        cap_gain(std::ldexp(1.0, -167), 1, "FirstMultiprecision"); // cpp_bin_float_50: eps = 2^-167
        cap_gain(std::ldexp(1.0, -167), 4, "FourthMultiprecision");
        // The model's digits for Central<2> in double, -log10(eps^(P/(P+N))) rounded to the nearest whole digit:
        // "about N digits" (style decision 24; R1-numerics-17h asked for one decimal, the release for whole digits).
        char const *const words[] = { "", "First", "Second", "Third", "Fourth" };
        for (int N = 1; N <= 4; ++N)
            value(o, std::string("ModelDigitsCentralTwo") + words[N] + "Double",
                integer(std::lround(-std::log10(dbl_eps) * 2.0 / (2 + N))));
    }

    void ds14_ridders_constants(Output &o)
    {
        // The divisors and the level cap are read from the library; the cap is also checked by counting the
        // evaluations of a never-finite fn (32 levels of 2). The ratio, the stall and the untrusted-result factors are
        // the header's documented values (literals inside detail::ridders).
        int calls = 0;
        auto const never = [](double) { return not_a_number; };
        auto const r = derivative<Ridders>(Counted{ never, &calls }, 1.0);
        if (r || calls != 2 * nxx::deriv::detail::ridders_levels) o.fail("DS14: the level cap does not match the evaluation count");
        auto const &div = nxx::deriv::detail::ridders_divisors;
        if (div[1] != div[2] || div[2] != div[3]) o.fail("DS14: the divisors of f'' to f'''' differ");
        constexpr int cap = nxx::deriv::detail::ridders_levels;
        value(o, "RiddersLevelCap", integer(cap));
        value(o, "RiddersDivisorFirst", integer(div[0]));
        value(o, "RiddersDivisorHigher", integer(div[1]));
        value(o, "RiddersMaxEvalsFirst", integer(2 * cap));
        value(o, "RiddersMaxEvalsSecond", integer(2 * cap + 1));
        value(o, "RiddersMaxEvalsThird", integer(4 * cap));
        value(o, "RiddersMaxEvalsFourth", integer(4 * cap + 1));

        // The one-sided forms (Phase 5): the divisor read from the library; per level the Forward<1> rule of order N,
        // whose table has the nodes 0 ... N, node 0 being f(x), evaluated once per call; so at most 1 + N cap. That
        // maximum is reached, all evaluations made, by log beyond the method's reach, at 1e-12 (as the library's
        // test has it), which the generator checks; a fn finite at x only costs less for N = 3 and 4, since such a
        // level stops at its first non-finite value (the f'' level evaluates both of its points first).
        constexpr int one_sided = nxx::deriv::detail::one_sided_divisor;
        std::array<int, 5> per_level{};
        std::array<int, 5> at_most{};
        std::array<int, 5> only_at_x{};
        auto const log_fn = [](double x) { return std::log(x); };
        auto const only_at_one = [](double x) { return x == 1.0 ? 1.0 : not_a_number; };
        char const *const names[] = { "", "First", "Second", "Third", "Fourth" };
        for_each(derivative_orders{}, [&](auto n) {
            constexpr int N = decltype(n)::value;
            constexpr auto t = nxx::deriv::detail::make_table<N>(Forward<1>{});
            per_level[N] = static_cast<int>(t.nodes.size()) - 1;
            at_most[N] = 1 + per_level[N] * cap;
            int beyond = 0;
            auto const beyond_r = derivative<ForwardRidders, N>(Counted{ log_fn, &beyond }, 1e-12);
            if (!beyond_r || beyond != at_most[N])
                o.fail("DS14: ForwardRidders on log at 1e-12 used " + std::to_string(beyond) + " evaluations, not "
                       + std::to_string(at_most[N]) + ", for N = " + std::to_string(N));
            int calls_x = 0;
            if (derivative<ForwardRidders, N>(Counted{ only_at_one, &calls_x }, 1.0))
                o.fail("DS14: ForwardRidders returned a value for fn finite at x only");
            only_at_x[N] = calls_x;
            value(o, std::string("ForwardRiddersMaxEvals") + names[N], integer(at_most[N]));
            value(o, std::string("ForwardRiddersOnlyAtXEvals") + names[N], integer(only_at_x[N]));
        });
        value(o, "ForwardRiddersDivisor", integer(one_sided));
        auto const four = [](std::array<int, 5> const &a) {
            return std::to_string(a[1]) + ", " + std::to_string(a[2]) + ", " + std::to_string(a[3]) + ", " + std::to_string(a[4]);
        };

        // Three columns (Phase 5): the constant, its value for Ridders, and for ForwardRidders and BackwardRidders.
        // The column divisor and the floor of an entry are the two choices the base makes (the header's ridders()
        // documentation); the restart rule is the same for all three methods since Phase 5.
        auto tab = table(o, "ridders-constants",
            "columns: constant; value for Ridders; value for ForwardRidders and BackwardRidders (f', f'', f''', f'''' where "
            "it depends on N)");
        std::string const central_max = four({ 0, 2 * cap, 2 * cap + 1, 4 * cap, 4 * cap + 1 });
        tab << "Ratio of the steps of consecutive levels & 2 & 2 \\\\\n";
        tab << "Initial step, divisor of $\\max(\\lvert x \\rvert, 1)$ & " << div[0] << " (\\(f'\\)), " << div[1]
            << " (\\(f''\\) to \\(f''''\\)) & " << one_sided << " \\\\\n";
        tab << "Column divisor of the tableau, column $j$ & $4^j - 1$ & $2^j - 1$ \\\\\n";
        tab << "Rounding floor of an entry & that of its level & carried through the tableau \\\\\n";
        tab << "Levels without improvement before the stop & 2 & 2 \\\\\n";
        tab << "Untrusted result: estimate at least $\\lvert A \\rvert / 4$ and more than 64 times the floor & 4, 64 & "
               "4, 64 \\\\\n";
        tab << "Restart after a failed level or an untrusted result & at half the smallest step tried & the same \\\\\n";
        tab << "Level cap (restarts included) & " << cap << " & " << cap << " \\\\\n";
        tab << "Evaluations per level & 2, 2, 4, 4 & " << four(per_level) << " \\\\\n";
        tab << "Evaluations of $f(x)$, once & 0, 1, 0, 1 & 1, 1, 1, 1 \\\\\n";
        tab << "Maximum evaluations & " << central_max << " & " << four(at_most) << " \\\\\n";
    }

