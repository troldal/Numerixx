    // M_j = sum_k c_k n_k^j, with the integer numerators (so M_N = N! d), as in the tests.
    template<std::size_t Size>
    long long moment(nxx::deriv::detail::Table<Size> const &t, int j)
    {
        long long m = 0;
        for (std::size_t k = 0; k < Size; ++k) {
            long long power = 1;
            for (int i = 0; i < j; ++i) power *= t.nodes[k];
            m += t.numerators[k] * power;
        }
        return m;
    }

    std::string derivative_symbol(int n)
    {
        if (n == 1) return "f'";
        if (n == 2) return "f''";
        if (n == 3) return "f'''";
        return "f^{(" + std::to_string(n) + ")}";
    }

    template<typename S, int N>
    void weight_row(Output &o, std::ofstream &tab, std::string const &family)
    {
        constexpr auto t = nxx::deriv::detail::make_table<N>(S{});
        constexpr int P = t.order;
        // The moment conditions: M_j = 0 for j != N below N + P, M_N = N! d, M_(N+P) != 0; nodes increasing.
        bool ok = t.denominator > 0;
        for (std::size_t k = 1; k < t.nodes.size(); ++k) ok = ok && t.nodes[k - 1] < t.nodes[k];
        for (int j = 0; j < N + P; ++j) ok = ok && moment(t, j) == (j == N ? factorial(N) * t.denominator : 0);
        long long const m_top = moment(t, N + P);
        ok = ok && m_top != 0;
        if (!ok) {
            o.fail("DS12: " + family + "<" + std::to_string(P) + "> for N = " + std::to_string(N) + " fails the moment conditions");
            return;
        }
        long long weights = 0;
        for (int const c : t.numerators) weights += c < 0 ? -c : c;
        double const S_ampl = static_cast<double>(weights) / t.denominator;
        long long num = m_top < 0 ? -m_top : m_top;
        long long den = factorial(N + P) * t.denominator;
        long long const g = std::gcd(num, den);
        num /= g;
        den /= g;
        std::string nodes;
        std::string numerators;
        for (std::size_t k = 0; k < t.nodes.size(); ++k) {
            nodes += (k ? ", " : "") + std::to_string(t.nodes[k]);
            numerators += (k ? ", " : "") + std::to_string(t.numerators[k]);
        }
        std::string const fraction = den == 1 ? std::to_string(num) : "\\tfrac{" + std::to_string(num) + "}{" + std::to_string(den) + "}";
        std::string const term = std::string(m_top > 0 ? "+" : "-") + (den == 1 && num == 1 ? "" : fraction) + "\\,h^{"
                                 + std::to_string(P) + "}\\," + derivative_symbol(N + P);
        tab << P << " & $" << nodes << "$ & $" << numerators << "$ & " << t.denominator << " & " << sig(S_ampl, 3) << " & $"
            << fraction << "$ & $" << term << "$ \\\\\n";
        // The constants S and C of the rules the text names (Central<2> ... <10> and Forward<1> ... <6> for f').
        if constexpr (N == 1) {
            char const *const words[] = { "", "One", "Two", "Three", "Four", "Five", "Six", "Seven", "Eight", "Nine", "Ten" };
            value(o, "Ampl" + family + words[P], sig(S_ampl, 3));
            value(o, "Errc" + family + words[P], sig(static_cast<double>(num) / static_cast<double>(den), 3));
        }
        // The largest amplification of all the tables, Forward<6> for the fourth derivative (sections 9.3 and 10.4).
        if constexpr (N == 4 && P == 6) {
            if (family == "Forward") value(o, "AmplForwardSixFourth", sig(S_ampl, 4));
        }
    }

    // The constants S and C of a rule, from its table, for the step-constant computations of DS13.
    template<typename S, int N>
    std::pair<double, double> rule_constants()
    {
        constexpr auto t = nxx::deriv::detail::make_table<N>(S{});
        long long weights = 0;
        for (int const c : t.numerators) weights += c < 0 ? -c : c;
        long long const m_top = moment(t, N + t.order);
        double const ampl = static_cast<double>(weights) / t.denominator;
        double const errc = static_cast<double>(m_top < 0 ? -m_top : m_top) / (static_cast<double>(factorial(N + t.order)) * t.denominator);
        return { ampl, errc };
    }

    void ds12_weight_tables(Output &o)
    {
        for_each(derivative_orders{}, [&](auto n) {
            constexpr int N = decltype(n)::value;
            {
                auto tab = table(o, "weights-central-N" + std::to_string(N),
                    "Central<P> for the derivative of order " + std::to_string(N)
                        + "; columns: P, nodes n_k, numerators c_k, denominator d, S = sum |c_k| / d, C = |M_(N+P)| / ((N+P)! d), "
                          "leading error term; checked against the moment conditions by the generator");
                for_each(central_orders{}, [&](auto p) { weight_row<Central<decltype(p)::value>, N>(o, tab, "Central"); });
            }
            {
                auto tab = table(o, "weights-forward-N" + std::to_string(N),
                    "Forward<P> for the derivative of order " + std::to_string(N)
                        + "; columns as for the central rules; Backward<P> is the mirror image: nodes negated and reversed, "
                          "numerators reversed and multiplied by (-1)^N, the same denominator (checked by the generator)");
                for_each(one_sided_orders{}, [&](auto p) {
                    constexpr int P = decltype(p)::value;
                    weight_row<Forward<P>, N>(o, tab, "Forward");
                    constexpr auto f = nxx::deriv::detail::make_table<N>(Forward<P>{});
                    constexpr auto b = nxx::deriv::detail::make_table<N>(Backward<P>{});
                    constexpr std::size_t size = f.nodes.size();
                    constexpr int sign = N % 2 == 1 ? -1 : 1;
                    bool mirrored = b.denominator == f.denominator;
                    for (std::size_t k = 0; k < size; ++k)
                        mirrored = mirrored && b.nodes[k] == -f.nodes[size - 1 - k] && b.numerators[k] == sign * f.numerators[size - 1 - k];
                    if (!mirrored) o.fail("DS12: Backward<" + std::to_string(P) + "> is not the mirror of Forward for N = " + std::to_string(N));
                });
            }
        });
    }

