    void ds19_noise(Output &o)
    {
        auto out = csv(o, "step-error-noise", "h,clean,noise_ten,noise_eight",
            "Central<2> on exp(x) at x = 1 with the value times (1 + eta u), u uniform in [-1, 1] from std::mt19937 seeded "
            "with the bits of x (code/noise.hpp); eta = 0 (clean), 1e-10 and 1e-8; relative errors");
        auto const noisy = [](double eta) { return [eta](double x) { return book::noisy(std::exp(x), x, eta); }; };
        auto const ten = noisy(1e-10);
        auto const eight = noisy(1e-8);
        Minimum best_ten;
        Minimum best_eight;
        Minimum best_clean;
        for (double const h : steps(0, -13)) {
            auto const c = rel_error(derivative<Central<2>>(exp_fn, 1.0, h), e_at_one);
            auto const t = rel_error(derivative<Central<2>>(ten, 1.0, h), e_at_one);
            auto const e8 = rel_error(derivative<Central<2>>(eight, 1.0, h), e_at_one);
            best_clean.offer(h, c);
            best_ten.offer(h, t);
            best_eight.offer(h, e8);
            out << cell(h) << ',' << cell(c) << ',' << cell(t) << ',' << cell(e8) << '\n';
        }
        value(o, "NoiseCleanBestStep", sig(best_clean.h));
        value(o, "NoiseCleanBestRelError", sig(best_clean.error));
        value(o, "NoiseTenBestStep", sig(best_ten.h));
        value(o, "NoiseTenBestRelError", sig(best_ten.error));
        value(o, "NoiseEightBestStep", sig(best_eight.h));
        value(o, "NoiseEightBestRelError", sig(best_eight.error));
        value(o, "NoiseEightDefaultRelError", sig(*rel_error(derivative<Central<2>>(eight, 1.0), e_at_one)));
        double const fit = std::cbrt(1e-8);
        value(o, "NoiseEightFitStep", sig(fit));
        value(o, "NoiseEightFitRelError", sig(*rel_error(derivative<Central<2>>(eight, 1.0, fit), e_at_one)));
        value(o, "NoiseEightModelBestStep", sig(std::cbrt(3e-8)));
        value(o, "NoiseEightModelBestRelError", sig(std::pow(1e-8, 2.0 / 3)));
        value(o, "NoiseTenFitStep", sig(std::cbrt(1e-10)));
        value(o, "NoiseTenFitRelError", sig(*rel_error(derivative<Central<2>>(ten, 1.0, std::cbrt(1e-10)), e_at_one)));
        int calls = 0;
        auto const r = derivative<Ridders>(Counted{ eight, &calls }, 1.0);
        ridders_values(o, "NoiseRidders", r, e_at_one, calls);
        if (r) value(o, "NoiseRiddersEstimateRatio", sig(std::abs(r->value - e_at_one) / *r->abs_error));

        // Whether Ridders' estimate still covers the error of a noisy function: 300 points in [0.2, 3] (the random
        // study's points of exp) for eta = 1e-10 and 1e-8, against the clean function. The header says the estimate
        // assumes fn accurate to about eps and is optimistic for a noisier fn; this measures by how much.
        auto const study_coverage = [&](auto fn, std::string const &prefix) {
            std::mt19937 gen(seed);
            int covered = 0;
            int cases = 0;
            std::vector<double> ratios;
            std::vector<double> errors;
            for (int k = 0; k < points_per_function; ++k) {
                double const x = 0.2 + 2.8 * (static_cast<double>(gen()) / 4294967296.0);
                auto const rr = derivative<Ridders>(fn, x);
                if (!rr) continue;
                ++cases;
                double const actual = std::abs(rr->value - std::exp(x));
                covered += actual <= *rr->abs_error ? 1 : 0;
                ratios.push_back(actual / *rr->abs_error);
                errors.push_back(actual / std::exp(x));
            }
            if (cases != points_per_function) o.fail("DS19: Ridders failed at " + std::to_string(points_per_function - cases) + " of the points for " + prefix);
            value(o, prefix + "Coverage", percent(static_cast<double>(covered) / cases));
            value(o, prefix + "MedianRatio", sig(median(ratios)));
            value(o, prefix + "WorstRatio", sig(*std::max_element(ratios.begin(), ratios.end())));
            value(o, prefix + "MedianRelError", sig(median(errors)));
        };
        study_coverage(exp_fn, "NoiseCleanRidders");
        study_coverage(ten, "NoiseTenRidders");
        study_coverage(eight, "NoiseEightRidders");
        value(o, "NoiseRiddersCases", integer(points_per_function));
    }

