    // The shared header against the evidence reviewer's exact evaluation of the published coefficients (rational
    // arithmetic, scratchpad record thread-data-nitrogen.md, 2026-10-23), at 1000 K and at the junction 500 K. These
    // are test oracles for the code, not numbers of the book.
    void check_nitrogen_function(Output &o)
    {
        struct Case
        {
            book::Shomate const *c;
            double T;
            std::array<double, 7> exact;
        };
        Case const cases[] = {
            { &book::nitrogen, 1000.0,
              { 21462.8196667, 32.69173, 0.00574413, -5.81276e-6, -4.44372e-9, 6.331212e-11, -3.7987272e-13 } },
            { &book::nitrogen, 500.0,
              { 5911.52283333, 29.58134825, 0.003874237, 3.7561978e-5, -3.96978864e-7, 4.05197568e-9,
                -4.862370816e-11 } },
            { &book::nitrogen_low, 500.0,
              { 5910.75444792, 29.5814235, 0.0046811745, 3.0622424e-5, 9.9722364e-8, 8.9856e-13, -1.078272e-14 } },
        };
        for (auto const &k : cases)
            for (int n = 0; n <= 6; ++n) {
                double const v = book::shomate_derivative(*k.c, k.T, n);
                if (std::abs(v - k.exact[static_cast<std::size_t>(n)]) > 1e-9 * std::abs(k.exact[static_cast<std::size_t>(n)]))
                    o.fail("shomate_derivative(" + std::to_string(n) + ") at " + std::to_string(k.T) + " K: "
                           + std::to_string(v) + " against the verified " + std::to_string(k.exact[static_cast<std::size_t>(n)]));
            }
        if (book::shomate_cp(book::nitrogen, T0) != Hn(1)) o.fail("shomate_cp differs from shomate_derivative(1)");
    }

    // exp(x), the function of the method figures: every derivative equals the function, so errors compare across
    // orders.
    constexpr auto exp_fn = [](double x) { return std::exp(x); };
    double const e_at_one = std::exp(1.0);

    // ------------------------------------------------------------------------------------------------ hand tables

    // The two pencil-and-paper tables of Chapters 2.3 and 3.2, generated so that no computed digit is typed.
    // Chapter 2: x^3 at x = 1 with h = 0.1 and 0.05, exact in decimal arithmetic; the values are printed to seven
    // significant digits, which a hand calculation gives exactly. Chapter 3: a six-digit calculator differentiating
    // exp(x) at 1, simulated by rounding every value of f and the quotient to six significant digits.
    double round_to_digits(double v, int digits)
    {
        char buf[64];
        std::snprintf(buf, sizeof buf, "%.*g", digits, v);
        return std::strtod(buf, nullptr);
    }

    std::string general(double v, int digits, bool keep_zeros = false)
    {
        char buf[64];
        std::snprintf(buf, sizeof buf, keep_zeros ? "%#.*g" : "%.*g", digits, v);
        return buf;
    }

    // A signed error to two significant digits in plain decimal notation, as a calculator shows it (+0.00022).
    std::string signed_decimal(double v)
    {
        int const decimals = std::max(0, 1 - static_cast<int>(std::floor(std::log10(std::abs(v)))));
        return (v < 0 ? "$-$" : "$+$") + fixed(std::abs(v), decimals);
    }

    void hand_tables(Output &o)
    {
        {
            auto tab = table(o, "hand-cube",
                "x^3 at x = 1 with h = 0.1 and 0.05: f(1+h), f(1-h), Forward<1> value and error, Central<2> value and error; "
                "the library's values printed to 7 significant digits, which an exact hand calculation gives too");
            auto const cube = [](double x) { return x * x * x; };
            for (double const h : { 0.1, 0.05 }) {
                auto const fwd = derivative<Forward<1>>(cube, 1.0, h);
                auto const cen = derivative<Central<2>>(cube, 1.0, h);
                if (!fwd || !cen) {
                    o.fail("hand-cube: a rule failed");
                    continue;
                }
                tab << "$h = " << general(h, 7) << "$ & $" << general(cube(1 + h), 7) << "$ & $" << general(cube(1 - h), 7)
                    << "$ & $" << general(fwd->value, 7) << "$, \\enspace $" << general(fwd->value - 3, 7) << "$ & $"
                    << general(cen->value, 7) << "$, \\enspace $" << general(cen->value - 3, 7) << "$ \\\\\n";
            }
        }
        {
            auto tab = table(o, "hand-calculator",
                "a six-digit calculator: the central difference of exp(x) at x = 1 for h = 0.1 to 0.0001, every value of f "
                "and the quotient rounded to 6 significant digits; error against e");
            double first_error = 0;
            double second_error = 0;
            double last_diff = 0;
            int row = 0;
            for (double const h : { 0.1, 0.01, 0.001, 0.0001 }) {
                double const fp = round_to_digits(std::exp(1 + h), 6);
                double const fm = round_to_digits(std::exp(1 - h), 6);
                double const estimate = round_to_digits((fp - fm) / (2 * h), 6);
                double const error = estimate - e_at_one;
                if (row == 0) first_error = error;
                if (row == 1) second_error = error;
                last_diff = fp - fm;
                tab << "$" << general(h, 7) << "$ & $" << general(fp, 6, true) << "$ & $" << general(fm, 6, true) << "$ & $"
                    << general(estimate, 6, true) << "$ & " << signed_decimal(error) << " \\\\\n";
                ++row;
            }
            value(o, "HandCalcExact", sig(e_at_one, 6));
            value(o, "HandCalcErrorRatio", sig(first_error / second_error));
            value(o, "HandCalcLastDiff", fixed(last_diff, 5));
            // The truncation error alone at h = 0.01, e h^2 / 6, against the row's error (R1-evidence-03).
            value(o, "HandCalcTruncationHundredth", sig(e_at_one * 0.01 * 0.01 / 6));
        }
    }

    // ------------------------------------------------------------------------------------------------ DS1, DS1b

    void ds1_step_error_cp(Output &o)
    {
        auto out = csv(o, "step-error-cp", "h,forward1,central2,central4,model_forward1,model_central2",
            "nitrogen H(T) at T0 = 1000 K, N = 1, relative errors against the closed-form cp; h in K");
        double const cp = Hn(1);
        double const H0 = std::abs(Hn(0));
        double const H2 = std::abs(Hn(2));
        double const H3 = std::abs(Hn(3));
        Minimum best;
        for (double const h : steps(2, -13)) {
            auto const f1 = rel_error(derivative<Forward<1>>(H, T0, h), cp);
            auto const c2 = rel_error(derivative<Central<2>>(H, T0, h), cp);
            auto const c4 = rel_error(derivative<Central<4>>(H, T0, h), cp);
            double const model_f1 = (0.5 * h * H2 + 2 * dbl_eps * H0 / h) / cp;
            double const model_c2 = (h * h / 6 * H3 + dbl_eps * H0 / h) / cp;
            best.offer(h, c2);
            out << cell(h) << ',' << cell(f1) << ',' << cell(c2) << ',' << cell(c4) << ',' << cell(model_f1) << ','
                << cell(model_c2) << '\n';
        }

        // DS1b: the default-step results of E1, E5, E7, E9 and the best step of the curve.
        value(o, "CpExact", sig(cp, 5));
        value(o, "CpExactLong", sig(cp, 12));
        value(o, "EnthalpyExact", sig(Hn(0), 6));
        // The tabulated heat capacity of nitrogen at 1000 K, 32.697 J/(mol K): M. W. Chase, Jr., NIST-JANAF
        // Thermochemical Tables, 4th ed., 1998, Part II, p. 1621 (chase1998); the fit's closed form against it
        // (R1-evidence-19). A cited constant, not a computation.
        constexpr double cp_table = 32.697;
        value(o, "CpTableValue", sig(cp_table, 5));
        value(o, "CpFitVsTableRelDiff", sig(std::abs(cp - cp_table) / cp_table));
        double const h_default = nxx::math::root_epsilon<3, double>() * T0;
        value(o, "CpDefaultStep", sig(h_default));
        auto const d = derivative(H, T0);
        if (!d) o.fail("Central<2> on the nitrogen example with the default step");
        value(o, "CpDefaultRelError", sig(*rel_error(d, cp)));
        value(o, "CpDefaultValueLong", sig(d->value, 12));
        value(o, "CpBestStep", sig(best.h));
        value(o, "CpBestRelError", sig(best.error));
        value(o, "CpCentralFourRelError", sig(*rel_error(derivative<Central<4>>(H, T0), cp)));
        value(o, "CpCentralSixRelError", sig(*rel_error(derivative<Central<6>>(H, T0), cp)));
        value(o, "CpCentralFourStep", sig(nxx::math::root_epsilon<5, double>() * T0));
        value(o, "CpCentralSixStep", sig(nxx::math::root_epsilon<7, double>() * T0));
        int calls = 0;
        auto const r = derivative<Ridders>(Counted{ H, &calls }, T0);
        ridders_values(o, "CpRidders", r, cp, calls);
        value(o, "CpRiddersInitialStep", sig(T0 / 32));

        // The second derivative, d cp / dT (E7).
        double const cp2 = Hn(2);
        value(o, "CpSecondExact", sig(cp2, 4));
        double const h2 = nxx::math::root_epsilon<4, double>() * T0;
        value(o, "CpSecondStep", sig(h2));
        value(o, "CpSecondRelError", sig(*rel_error(derivative<Central<2>, 2>(H, T0), cp2)));
        // The model's rounding term for the three-point rule at its default step, relative: S eps |H| / (h^2 |H''|)
        // with S = 4 (section 5.2).
        value(o, "CpSecondModelRelError", sig(4 * dbl_eps * H0 / (h2 * h2 * std::abs(cp2))));
        calls = 0;
        auto const r2 = derivative<Ridders, 2>(Counted{ H, &calls }, T0);
        ridders_values(o, "CpRiddersSecond", r2, cp2, calls);

        // The factors behind "relative accuracy" (section 3.2, 5.2): |H| / (s |H'|) and |H| / (s^2 |H''|) at T0.
        value(o, "CpRelativeFactor", sig(H0 / (T0 * cp)));
        value(o, "CpSecondRelativeFactor", sig(H0 / (T0 * T0 * std::abs(cp2))));
    }

    // The nitrogen enthalpy with the wrapper of code/04-stencils-edge.cpp, which returns NaN outside the fit's range
    // [500, 2000] K: "evaluable" and "valid" are then the same thing (E6, E24).
    constexpr auto edge_H = [](double T) {
        using book::nitrogen;
        if (T < nitrogen.T_min || T > nitrogen.T_max) return not_a_number;
        return book::shomate_H(nitrogen, T);
    };

    // E6 (section 4.4): the one-sided rules at the lower end of the fit's range, 500 K, with the wrapper that returns
    // NaN outside the range, as code/04-stencils-edge.cpp has it; Central<2> must fail there.
    void e6_validity_edge(Output &o)
    {
        auto const wrapped = edge_H;
        double const T_edge = book::nitrogen.T_min;
        double const cp = book::shomate_cp(book::nitrogen, T_edge);
        if (derivative<Central<2>>(wrapped, T_edge)) o.fail("E6: Central<2> did not fail at the edge");
        auto const f2 = rel_error(derivative<Forward<2>>(wrapped, T_edge), cp);
        auto const f4 = rel_error(derivative<Forward<4>>(wrapped, T_edge), cp);
        if (!f2 || !f4) {
            o.fail("E6: a one-sided rule failed at the edge");
            return;
        }
        value(o, "EdgeForwardTwoRelError", sig(*f2));
        value(o, "EdgeForwardFourRelError", sig(*f4));
        // Ridders exactly at the edge (R1-evidence-18): every level of every tableau samples below the range, so the
        // method restarts until its budget is spent.
        int calls = 0;
        auto const r = derivative<Ridders>(Counted{ wrapped, &calls }, T_edge);
        value(o, "EdgeRiddersStatus", r ? "finite" : "non-finite");
        value(o, "EdgeRiddersEvals", integer(calls));
        if (r) value(o, "EdgeRiddersRelError", sig(*rel_error(r, cp)));
    }

