    // ------------------------------------------------------------------------------------------------ DS21

    // E20: the Darcy friction factor from the Colebrook equation 1/sqrt(f) = -2 log10(eps_r / 3.7 + 2.51 / (Re sqrt f)),
    // written in x = 1/sqrt(f): G(x) = x + 2 log10(a + b x / Re) = 0 with a = eps_r / 3.7, b = 2.51. G increases
    // with x, so bisection on [1, 20] (f from 1 to 1/400) finds the root. Parameters (data/README.md; the example
    // must use the same): eps_r = 1e-4, Re = 1e5, eta = 1e-10.
    constexpr double colebrook_a = 1e-4 / 3.7;
    constexpr double colebrook_b = 2.51;

    double colebrook_G(double x, double Re) { return x + 2 * std::log10(colebrook_a + colebrook_b * x / Re); }

    // Bisection to a relative tolerance eta on x: the output is quantised at eta, which is the noise of Chapter 3.6.
    double friction_bisection(double Re, double eta)
    {
        double lo = 1.0;
        double hi = 20.0;
        while (hi - lo > eta * hi) {
            double const mid = (lo + hi) / 2;
            if (colebrook_G(mid, Re) > 0)
                hi = mid;
            else
                lo = mid;
        }
        double const x = (lo + hi) / 2;
        return 1 / (x * x);
    }

    // Fixed-point iteration x <- -2 log10(a + b x / Re) from x = 7 until the step is below eta |x|: the output is
    // smooth in Re except where the iteration count changes (computed for comparison).
    double friction_fixed_point(double Re, double eta)
    {
        double x = 7.0;
        for (int i = 0; i < 1000; ++i) {
            double const next = -2 * std::log10(colebrook_a + colebrook_b * x / Re);
            bool const done = std::abs(next - x) <= eta * std::abs(next);
            x = next;
            if (done) break;
        }
        return 1 / (x * x);
    }

    // The answer key: the root to machine precision by Newton on G, then df/dRe by implicit differentiation,
    // df/dRe = -G_Re / G_f with G written in f: G = f^(-1/2) + 2 log10(u), u = a + b / (Re sqrt f).
    double friction_exact(double Re)
    {
        double x = 7.0;
        for (int i = 0; i < 100; ++i) {
            double const u = colebrook_a + colebrook_b * x / Re;
            double const g = x + 2 * std::log10(u);
            double const dg = 1 + 2 / std::numbers::ln10 * (colebrook_b / Re) / u;
            double const next = x - g / dg;
            if (next == x) break;
            x = next;
        }
        return 1 / (x * x);
    }

    double friction_derivative_exact(double Re)
    {
        double const f = friction_exact(Re);
        double const u = colebrook_a + colebrook_b / (Re * std::sqrt(f));
        double const c = 2 / std::numbers::ln10;
        double const G_f = -0.5 * std::pow(f, -1.5) * (1 + c * colebrook_b / (Re * u));
        double const G_Re = -c * colebrook_b / (u * Re * Re * std::sqrt(f));
        return -G_Re / G_f;
    }

    void ds21_solver(Output &o)
    {
        double const Re = 1e5;
        double const eta = 1e-10;
        double const exact = friction_derivative_exact(Re);
        auto const f = [eta](double re) { return friction_bisection(re, eta); };
        value(o, "SolverReynolds", sig(Re));
        value(o, "SolverRoughness", sig(1e-4));
        value(o, "SolverTolerance", sig(eta));
        value(o, "SolverFriction", sig(friction_exact(Re), 6));
        value(o, "SolverFrictionNoise", sig(std::abs(f(Re) - friction_exact(Re)) / friction_exact(Re)));
        value(o, "SolverExact", sig(exact, 6));
        value(o, "SolverScaleFactor", sig(friction_exact(Re) / (Re * std::abs(exact))));
        double const h_default = nxx::math::root_epsilon<3, double>() * Re;
        double const h_fit = std::cbrt(eta) * Re;
        value(o, "SolverDefaultStep", sig(h_default));
        value(o, "SolverFitStep", sig(h_fit));
        value(o, "SolverDefaultRelError", sig(*rel_error(derivative<Central<2>>(f, Re), exact)));
        value(o, "SolverFitRelError", sig(*rel_error(derivative<Central<2>>(f, Re, h_fit), exact)));
        value(o, "SolverModelFitRelError", sig(std::pow(eta, 2.0 / 3)));
        int calls = 0;
        auto const r = derivative<Ridders>(Counted{ f, &calls }, Re);
        ridders_values(o, "SolverDeriv", r, exact, calls);
        if (r) value(o, "SolverDerivEstimateRatio", sig(std::abs(r->value - exact) / *r->abs_error));
        // The same with the fixed-point solver, for the editor's comparison (not planned for the text).
        auto const fp = [eta](double re) { return friction_fixed_point(re, eta); };
        value(o, "SolverFixedPointNoise", sig(std::abs(fp(Re) - friction_exact(Re)) / friction_exact(Re)));
        value(o, "SolverFixedPointDefaultRelError", sig(*rel_error(derivative<Central<2>>(fp, Re), exact)));
        value(o, "SolverFixedPointFitRelError", sig(*rel_error(derivative<Central<2>>(fp, Re, h_fit), exact)));
        calls = 0;
        auto const rfp = derivative<Ridders>(Counted{ fp, &calls }, Re);
        ridders_values(o, "SolverFixedPointRidders", rfp, exact, calls);
        // The curve of the error against the step for the bisection solver (a margin figure if an author wants it).
        auto out = csv(o, "step-error-solver", "h,bisection,fixed_point",
            "Central<2> on the Colebrook friction factor at Re = 1e5 from bisection and from fixed-point iteration, both to "
            "eta = 1e-10; relative errors against the implicit-function derivative; h in units of Re");
        for (double const h : steps(4, -4))
            out << cell(h) << ',' << cell(rel_error(derivative<Central<2>>(f, Re, h), exact)) << ','
                << cell(rel_error(derivative<Central<2>>(fp, Re, h), exact)) << '\n';
    }

